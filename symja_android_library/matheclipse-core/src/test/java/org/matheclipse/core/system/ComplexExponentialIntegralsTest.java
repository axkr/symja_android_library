  private interface ComplexFunction {
    IExpr apply(IComplexNum z);
  }

  private static void check(String name, double[][] reference, ComplexFunction f) {
    double worst = 0.0;
    String worstAt = "";
    for (double[] row : reference) {
      IExpr result = f.apply(F.complexNum(row[0], row[1]));
      double actualRe;
      double actualIm;
      if (result instanceof IComplexNum) {
        actualRe = ((IComplexNum) result).reDoubleValue();
        actualIm = ((IComplexNum) result).imDoubleValue();
      } else if (result.isReal()) {
        actualRe = result.evalf();
        actualIm = 0.0;
      } else {
        throw new AssertionError(name + " did not evaluate at " + row[0] + "+" + row[1] + "i");
      }
      Complex expected = new Complex(row[2], row[3]);
      // scaled by the modulus: these are complex values, so neither part alone sets the scale
      double error =
          Math.hypot(actualRe - row[2], actualIm - row[3]) / Math.max(expected.norm(), 1.0e-300);
      if (error > worst) {
        worst = error;
        worstAt = name + "(" + row[0] + (row[1] < 0 ? "" : "+") + row[1] + "i) expected (" + row[2]
            + ", " + row[3] + ") but was (" + actualRe + ", " + actualIm + ")";
      }
    }
    assertTrue(worst < MAX_ERROR, worstAt + " - relative error " + worst);
  }

