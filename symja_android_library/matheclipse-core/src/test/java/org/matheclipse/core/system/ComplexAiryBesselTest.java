  /**
   * The Airy equation <code>w'' = z w</code>, checked by the Wronskian
   * <code>Ai(z) Bi'(z) - Ai'(z) Bi(z) = 1/Pi</code> - an identity that holds for every
   * <code>z</code> and needs no reference values at all.
   */
  @Test
  public void testAiryWronskian() {
    for (double[] row : AIRY_AI) {
      IComplexNum z = F.complexNum(row[0], row[1]);
      IExpr ai = z.airyAi();
      IExpr aiPrime = z.airyAiPrime();
      IExpr bi = z.airyBi();
      IExpr biPrime = z.airyBiPrime();
      if (!(ai instanceof IComplexNum) || !(bi instanceof IComplexNum)) {
        continue;
      }
      org.hipparchus.complex.Complex a = new org.hipparchus.complex.Complex(
          ((IComplexNum) ai).reDoubleValue(), ((IComplexNum) ai).imDoubleValue());
      org.hipparchus.complex.Complex ap = new org.hipparchus.complex.Complex(
          ((IComplexNum) aiPrime).reDoubleValue(), ((IComplexNum) aiPrime).imDoubleValue());
      org.hipparchus.complex.Complex b = new org.hipparchus.complex.Complex(
          ((IComplexNum) bi).reDoubleValue(), ((IComplexNum) bi).imDoubleValue());
      org.hipparchus.complex.Complex bp = new org.hipparchus.complex.Complex(
          ((IComplexNum) biPrime).reDoubleValue(), ((IComplexNum) biPrime).imDoubleValue());
      org.hipparchus.complex.Complex wronskian = a.multiply(bp).subtract(ap.multiply(b));
      // The identity is a DIFFERENCE of two products, and away from the origin those products
      // dwarf the 1/Pi they are supposed to leave behind - at z = 10i each is about 7e11, so the
      // identity alone discards twelve digits no matter how exact the four values are. Judge it
      // against that loss rather than against a fixed bound, or this measures the conditioning of
      // the identity instead of the implementation.
      double products = Math.max(a.multiply(bp).norm(), ap.multiply(b).norm());
      double tolerance = Math.max(1.0e-11, products * 1.0e-13 * Math.PI);
      double error = wronskian.subtract(1.0 / Math.PI).norm() * Math.PI;
      assertTrue(error < tolerance, "Airy Wronskian at (" + row[0] + ", " + row[1] + "): off by "
          + error + " against a tolerance of " + tolerance);
    }
  }

  /**
   * An integer order is outside the double implementation's domain, so this checks the fall-back is
   * actually reached rather than a null escaping as a failure.
   */
  @Test
  public void testIntegerOrderStillEvaluates() {
    IComplexNum z = F.complexNum(1.7, 0.4);
    for (double order : new double[] {0.0, 1.0, 2.0, -1.0}) {
      IComplexNum v = F.complexNum(order, 0.0);
      assertTrue(v.besselY(z).isNumber(), "BesselY at integer order " + order);
      assertTrue(v.besselK(z).isNumber(), "BesselK at integer order " + order);
      assertTrue(v.besselJ(z).isNumber(), "BesselJ at integer order " + order);
      assertTrue(v.besselI(z).isNumber(), "BesselI at integer order " + order);
    }
  }
