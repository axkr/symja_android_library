package org.matheclipse.parser.test.tablegen;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import org.matheclipse.parser.client.operator.ASTNodeFactory;
import org.matheclipse.parser.client.operator.InfixOperator;
import org.matheclipse.parser.client.operator.Operator;
import org.matheclipse.parser.client.operator.PostfixOperator;
import org.matheclipse.parser.client.operator.PrefixOperator;
import org.yaml.snakeyaml.Yaml;

/**
 * Compares Symja's hand-maintained operator table against the Mathics3 operator tables and writes a
 * Markdown report.
 *
 * <p>
 * This is the artifact that has to exist before Symja's precedences are touched. Symja and Mathics
 * agree on most operators and disagree on a handful, and the disagreements are not all mistakes -
 * some are deliberate (Symja's <code>@</code> at 621 sits just above <code>@@</code> at 620 so that
 * <code>f@g@@h</code> groups the way Symja wants). Adopting the Mathics numbers wholesale would
 * silently change how existing input parses, so every row below is a decision, not a bug list.
 *
 * <p>
 * The report is a developer tool, not a test - it prints what is, it does not assert what should
 * be. Run it, read it, decide per row, and record the decisions in the override list.
 *
 * <pre>
 * mvn -pl matheclipse-parser test-compile
 * java -cp &lt;parser test classpath&gt; \
 *     org.matheclipse.parser.test.tablegen.OperatorTableReport [output.md]
 * </pre>
 *
 * <p>
 * Symja's side is read from {@link ASTNodeFactory}, which is one of the two hand-maintained tables.
 * The other, {@code ExprParserFactory} in matheclipse-core, is compared against this one by
 * {@code ExprOperatorTest} in that module - it cannot be reached from here, because matheclipse-core
 * sits downstream.
 */
public final class OperatorTableReport {

  /** How Symja spells an affix, derived from the operator's concrete class. */
  private static final String INFIX = "Infix";
  private static final String PREFIX = "Prefix";
  private static final String POSTFIX = "Postfix";

  private OperatorTableReport() {}

  public static void main(String[] args) throws IOException {
    Path output = Paths.get(args.length > 0 ? args[0] : "operator-table-report.md");

    Map<String, Object> mathics = loadMathicsTables();
    Map<String, SymjaOperator> symja = readSymjaTable();

    StringBuilder report = new StringBuilder(64 * 1024);
    report.append("# Symja vs Mathics3 operator tables\n\n");
    report.append("Generated by `OperatorTableReport`. Symja's side is `ASTNodeFactory`; "
        + "Mathics' side is `operators.yml` + `named-characters.yml`.\n\n");

    appendSummary(report, mathics, symja);
    appendPrecedenceDifferences(report, mathics, symja);
    appendAffixDifferences(report, mathics, symja);
    appendAssociativityDifferences(report, mathics, symja);
    appendUnknownToMathics(report, mathics, symja);
    appendMissingFromSymja(report, mathics, symja);

    Files.write(output, report.toString().getBytes(StandardCharsets.UTF_8));
    System.out.println("wrote " + output.toAbsolutePath());
    System.out.println(report.substring(0, Math.min(report.length(), 4000)));
  }

  // ------------------------------------------------------------------ Symja side

  /** One Symja operator, flattened out of the operator table. */
  private static final class SymjaOperator {
    final String name;
    final String affix;
    final int precedence;
    final String associativity;
    final Set<String> tokens = new TreeSet<>();

    SymjaOperator(String name, String affix, int precedence, String associativity) {
      this.name = name;
      this.affix = affix;
      this.precedence = precedence;
      this.associativity = associativity;
    }
  }

  /**
   * Symja's table, keyed by operator name. An operator registered under several tokens - the ASCII
   * spelling and one or more unicode aliases - is one entry with several tokens, because the table
   * registers the very same operator instance for each.
   */
  private static Map<String, SymjaOperator> readSymjaTable() {
    Map<String, SymjaOperator> byName = new TreeMap<>();
    for (Map.Entry<String, ArrayList<Operator>> entry : ASTNodeFactory.MMA_STYLE_FACTORY
        .getOperator2ListMap().entrySet()) {
      for (Operator operator : entry.getValue()) {
        String affix = affixOf(operator);
        // Includes the precedence: Symja registers two Apply operators, "@" at 621 and "@@" at
        // 620, and collapsing them would report one number and hide the other.
        String key = operator.getFunctionName() + "/" + affix + "/" + operator.getPrecedence();
        SymjaOperator symjaOperator = byName.computeIfAbsent(key,
            k -> new SymjaOperator(operator.getFunctionName(), affix, operator.getPrecedence(),
                associativityOf(operator)));
        symjaOperator.tokens.add(entry.getKey());
      }
    }
    return byName;
  }

  private static String affixOf(Operator operator) {
    if (operator instanceof PrefixOperator) {
      return PREFIX;
    }
    if (operator instanceof PostfixOperator) {
      return POSTFIX;
    }
    return INFIX;
  }

  /**
   * Symja's grouping translated into the vocabulary Mathics uses.
   *
   * <p>
   * The mapping of {@code NONE} is the interesting one. Symja uses it for Plus, Times, And, Equal -
   * operators whose arguments it collects into one flat call - which is what Mathics calls
   * <em>flat</em>, not what it calls <em>non-associative</em>. Reported as {@code flat?} so that a
   * row which hinges on this reads as a question rather than as an established difference.
   */
  private static String associativityOf(Operator operator) {
    if (!(operator instanceof InfixOperator)) {
      return "";
    }
    switch (((InfixOperator) operator).getGrouping()) {
      case InfixOperator.LEFT_ASSOCIATIVE:
        return "left";
      case InfixOperator.RIGHT_ASSOCIATIVE:
        return "right";
      case InfixOperator.NONE:
        return "flat?";
      default:
        return "?";
    }
  }

  // ---------------------------------------------------------------- Mathics side

  @SuppressWarnings("unchecked")
  private static Map<String, Object> loadMathicsTables() throws IOException {
    Yaml yaml = new Yaml();
    try (
        InputStream operators =
            OperatorTableReport.class.getClassLoader().getResourceAsStream("data/operators.yml");
        InputStream characters = OperatorTableReport.class.getClassLoader()
            .getResourceAsStream("data/named-characters.yml")) {
      if (operators == null || characters == null) {
        throw new IOException("data/operators.yml or data/named-characters.yml not on the "
            + "test classpath");
      }
      return OperatorTableBuilder.compileTables(yaml.load(operators), yaml.load(characters));
    }
  }

  @SuppressWarnings("unchecked")
  private static Map<String, Integer> mathicsPrecedences(Map<String, Object> mathics) {
    return (Map<String, Integer>) mathics.get("operator-precedences");
  }

  @SuppressWarnings("unchecked")
  private static Map<String, Integer> table(Map<String, Object> mathics, String key) {
    Map<String, Integer> map = (Map<String, Integer>) mathics.get(key);
    return map == null ? Collections.emptyMap() : map;
  }

  @SuppressWarnings("unchecked")
  private static Map<String, List<String>> mathicsTokens(Map<String, Object> mathics) {
    Map<String, List<String>> map = (Map<String, List<String>>) mathics.get("operator-to_string");
    return map == null ? Collections.emptyMap() : map;
  }

  /** The affix Mathics records for an operator, or {@code null} if it records none. */
  private static String mathicsAffix(Map<String, Object> mathics, String name) {
    if (table(mathics, "prefix-operators").containsKey(name)) {
      return PREFIX;
    }
    if (table(mathics, "postfix-operators").containsKey(name)) {
      return POSTFIX;
    }
    if (table(mathics, "flat-binary-operators").containsKey(name)
        || table(mathics, "left-binary-operators").containsKey(name)
        || table(mathics, "right-binary-operators").containsKey(name)
        || table(mathics, "non-associative-binary-operators").containsKey(name)) {
      return INFIX;
    }
    return null;
  }

  /** The associativity Mathics records for an operator, or the empty string. */
  private static String mathicsAssociativity(Map<String, Object> mathics, String name) {
    if (table(mathics, "flat-binary-operators").containsKey(name)) {
      return "flat";
    }
    if (table(mathics, "left-binary-operators").containsKey(name)) {
      return "left";
    }
    if (table(mathics, "right-binary-operators").containsKey(name)) {
      return "right";
    }
    if (table(mathics, "non-associative-binary-operators").containsKey(name)) {
      return "non-associative";
    }
    return "";
  }

  // -------------------------------------------------------------------- sections

  private static void appendSummary(StringBuilder report, Map<String, Object> mathics,
      Map<String, SymjaOperator> symja) {
    Map<String, Integer> precedences = mathicsPrecedences(mathics);
    int known = 0;
    for (SymjaOperator operator : symja.values()) {
      if (precedences.containsKey(operator.name)) {
        known++;
      }
    }
    report.append("## Summary\n\n");
    report.append("- Symja operators (name x affix): **").append(symja.size()).append("**\n");
    report.append("- Mathics operators: **").append(precedences.size()).append("**\n");
    report.append("- Symja operators Mathics also knows: **").append(known).append("**\n\n");
  }

  private static void appendPrecedenceDifferences(StringBuilder report,
      Map<String, Object> mathics, Map<String, SymjaOperator> symja) {
    Map<String, Integer> precedences = mathicsPrecedences(mathics);
    report.append("## Precedence differences\n\n");
    report.append("Every row is a decision. Changing Symja's number changes how existing input "
        + "parses.\n\n");
    report.append("| operator | affix | tokens | Symja | Mathics | delta |\n");
    report.append("|---|---|---|---|---|---|\n");
    int rows = 0;
    for (SymjaOperator operator : symja.values()) {
      Integer mathicsPrecedence = precedences.get(operator.name);
      if (mathicsPrecedence == null || mathicsPrecedence == operator.precedence) {
        continue;
      }
      rows++;
      report.append("| `").append(operator.name).append("` | ").append(operator.affix).append(" | ")
          .append(tokenList(operator)).append(" | ").append(operator.precedence).append(" | ")
          .append(mathicsPrecedence).append(" | ")
          .append(operator.precedence - mathicsPrecedence).append(" |\n");
    }
    report.append("\n**").append(rows).append("** differing.\n\n");
  }

  private static void appendAffixDifferences(StringBuilder report, Map<String, Object> mathics,
      Map<String, SymjaOperator> symja) {
    report.append("## Affix differences\n\n");
    report.append("Only names for which Symja has *no* reading of the affix Mathics records. "
        + "Symja gives several operators more readings than Mathics does - Function is both the "
        + "infix `|->` and the postfix `&` - and having an extra reading is not a difference.\n\n");
    report.append("| operator | Symja affixes | Symja tokens | Mathics |\n|---|---|---|---|\n");
    Map<String, Set<String>> affixesByName = new TreeMap<>();
    Map<String, Set<String>> tokensByName = new TreeMap<>();
    for (SymjaOperator operator : symja.values()) {
      affixesByName.computeIfAbsent(operator.name, k -> new TreeSet<>()).add(operator.affix);
      tokensByName.computeIfAbsent(operator.name, k -> new TreeSet<>()).addAll(operator.tokens);
    }
    int rows = 0;
    for (Map.Entry<String, Set<String>> entry : affixesByName.entrySet()) {
      String affix = mathicsAffix(mathics, entry.getKey());
      if (affix == null || entry.getValue().contains(affix)) {
        continue;
      }
      rows++;
      report.append("| `").append(entry.getKey()).append("` | ")
          .append(String.join(", ", entry.getValue())).append(" | ")
          .append(escapeTokens(new ArrayList<>(tokensByName.get(entry.getKey())))).append(" | ")
          .append(affix).append(" |\n");
    }
    report.append("\n**").append(rows).append("** differing.\n\n");
  }

  private static void appendAssociativityDifferences(StringBuilder report,
      Map<String, Object> mathics, Map<String, SymjaOperator> symja) {
    report.append("## Associativity differences\n\n");
    report.append("`flat?` is Symja's `InfixOperator.NONE`, which behaves like Mathics' `flat`; "
        + "those rows are usually agreement, not disagreement.\n\n");
    report.append("| operator | tokens | Symja | Mathics |\n|---|---|---|---|\n");
    int rows = 0;
    for (SymjaOperator operator : symja.values()) {
      if (!INFIX.equals(operator.affix)) {
        continue;
      }
      String associativity = mathicsAssociativity(mathics, operator.name);
      if (associativity.isEmpty() || associativity.equals(operator.associativity)
          || ("flat?".equals(operator.associativity) && "flat".equals(associativity))) {
        continue;
      }
      rows++;
      report.append("| `").append(operator.name).append("` | ").append(tokenList(operator))
          .append(" | ").append(operator.associativity).append(" | ").append(associativity)
          .append(" |\n");
    }
    report.append("\n**").append(rows).append("** differing.\n\n");
  }

  private static void appendUnknownToMathics(StringBuilder report, Map<String, Object> mathics,
      Map<String, SymjaOperator> symja) {
    Map<String, Integer> precedences = mathicsPrecedences(mathics);
    report.append("## Symja operators Mathics does not list\n\n");
    report.append("Sentinels and Symja extensions. These have to survive any table rebuild.\n\n");
    report.append("| operator | affix | tokens | Symja precedence |\n|---|---|---|---|\n");
    int rows = 0;
    for (SymjaOperator operator : symja.values()) {
      if (precedences.containsKey(operator.name)) {
        continue;
      }
      rows++;
      report.append("| `").append(operator.name).append("` | ").append(operator.affix).append(" | ")
          .append(tokenList(operator)).append(" | ").append(operator.precedence).append(" |\n");
    }
    report.append("\n**").append(rows).append("** operators.\n\n");
  }

  private static void appendMissingFromSymja(StringBuilder report, Map<String, Object> mathics,
      Map<String, SymjaOperator> symja) {
    Map<String, List<String>> tokens = mathicsTokens(mathics);
    Set<String> symjaNames = new TreeSet<>();
    for (SymjaOperator operator : symja.values()) {
      symjaNames.add(operator.name);
    }
    Map<String, List<String>> missing = new TreeMap<>();
    for (Map.Entry<String, List<String>> entry : tokens.entrySet()) {
      if (!symjaNames.contains(entry.getKey()) && mathicsAffix(mathics, entry.getKey()) != null) {
        missing.put(entry.getKey(), entry.getValue());
      }
    }
    report.append("## Mathics operators Symja does not implement\n\n");
    report.append("Candidates for new operator support, not defects. **").append(missing.size())
        .append("** operators with a spelling Mathics recognises.\n\n");
    report.append("<details><summary>list</summary>\n\n");
    report.append("| operator | affix | precedence | tokens |\n|---|---|---|---|\n");
    Map<String, Integer> precedences = mathicsPrecedences(mathics);
    for (Map.Entry<String, List<String>> entry : missing.entrySet()) {
      report.append("| `").append(entry.getKey()).append("` | ")
          .append(mathicsAffix(mathics, entry.getKey())).append(" | ")
          .append(precedences.get(entry.getKey())).append(" | ")
          .append(escapeTokens(entry.getValue())).append(" |\n");
    }
    report.append("\n</details>\n");
  }

  private static String tokenList(SymjaOperator operator) {
    return escapeTokens(new ArrayList<>(operator.tokens));
  }

  /** Render tokens as inline code, with unescaped code points spelled out so the table stays readable. */
  private static String escapeTokens(List<String> tokens) {
    List<String> rendered = new ArrayList<>(tokens.size());
    for (String token : tokens) {
      StringBuilder buf = new StringBuilder();
      boolean printable = true;
      for (int i = 0; i < token.length(); i++) {
        char ch = token.charAt(i);
        if (ch < 0x20 || (ch >= 0x7f && ch <= 0xa0) || Character.isSurrogate(ch)
            || (ch >= 0xe000 && ch <= 0xf8ff)) {
          printable = false;
          buf.append(String.format("U+%04X", (int) ch));
        } else {
          buf.append(ch);
        }
      }
      rendered.add(printable ? "`" + token.replace("|", "\\|") + "`" : buf.toString());
    }
    Map<String, String> unique = new LinkedHashMap<>();
    for (String token : rendered) {
      unique.put(token, token);
    }
    return String.join(" ", unique.keySet());
  }
}
