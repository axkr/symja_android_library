  private static void assertClose(Complex actual, double re, double im, double scale, String what) {
    assertNotNull(actual, what + " was withdrawn");
    double error = Math.hypot(actual.getReal() - re, actual.getImaginary() - im) / scale;
    assertTrue(error < MAX_ERROR, what + ": expected (" + re + ", " + im + ") but was ("
        + actual.getReal() + ", " + actual.getImaginary() + ") - error " + error);
  }

  @Test
  public void testLogGamma() {
    for (double[] row : LOG_GAMMA) {
      Complex z = new Complex(row[0], row[1]);
      assertClose(ComplexGamma.logGamma(z), row[2], row[3],
          Math.max(Math.hypot(row[2], row[3]), 1.0), "LogGamma(" + row[0] + "+" + row[1] + "i)");
    }
  }

  @Test
  public void testGamma() {
    for (double[] row : LOG_GAMMA) {
      Complex z = new Complex(row[0], row[1]);
      double magnitude = Math.hypot(row[4], row[5]);
      if (magnitude < 1.0e-290 || magnitude > 1.0e290) {
        continue;
      }
      assertClose(ComplexGamma.gamma(z), row[4], row[5], magnitude,
          "Gamma(" + row[0] + "+" + row[1] + "i)");
    }
  }

  /**
   * The functional equation <code>LogGamma(z+1) = LogGamma(z) + Log(z)</code> with the principal
   * logarithm - which is what the implementation leans on to reach the left half-plane, so checking
   * it directly is checking the mechanism rather than the result.
   */
  @Test
  public void testLogGammaRecurrence() {
    for (double[] row : LOG_GAMMA) {
      Complex z = new Complex(row[0], row[1]);
      Complex left = ComplexGamma.logGamma(z.add(1.0));
      Complex right = ComplexGamma.logGamma(z);
      if (left == null || right == null) {
        continue;
      }
      Complex expected = right.add(z.log());
      double scale = Math.max(expected.norm(), 1.0);
      assertTrue(left.subtract(expected).norm() / scale < 1.0e-13,
          "LogGamma recurrence at " + row[0] + "+" + row[1] + "i");
    }
  }

  @Test
  public void testBarnesG() {
    for (double[] row : BARNES_G) {
      Complex z = new Complex(row[0], row[1]);
      double magnitude = Math.hypot(row[2], row[3]);
      if (magnitude < 1.0e-290 || magnitude > 1.0e290) {
        continue;
      }
      assertClose(BarnesG.barnesG(z), row[2], row[3], magnitude,
          "BarnesG(" + row[0] + "+" + row[1] + "i)");
    }
  }

  @Test
  public void testLogBarnesG() {
    for (double[] row : BARNES_G) {
      Complex z = new Complex(row[0], row[1]);
      assertClose(BarnesG.logBarnesG(z), row[4], row[5], Math.max(Math.hypot(row[4], row[5]), 1.0),
          "LogBarnesG(" + row[0] + "+" + row[1] + "i)");
    }
  }

  /** <code>G(z+1) = Gamma(z) G(z)</code>, the recurrence the whole construction rests on. */
  @Test
  public void testBarnesGRecurrence() {
    for (double[] row : BARNES_G) {
      Complex z = new Complex(row[0], row[1]);
      Complex gammaZ = ComplexGamma.gamma(z);
      Complex gZ = BarnesG.barnesG(z);
      Complex gZPlus1 = BarnesG.barnesG(z.add(1.0));
      if (gammaZ == null || gZ == null || gZPlus1 == null) {
        continue;
      }
      Complex expected = gammaZ.multiply(gZ);
      double scale = Math.max(expected.norm(), 1.0e-300);
      assertTrue(gZPlus1.subtract(expected).norm() / scale < 1.0e-11,
          "G(z+1) = Gamma(z) G(z) at " + row[0] + "+" + row[1] + "i");
    }
  }
