package org.matheclipse.core.reflection.system;

import org.matheclipse.core.eval.Errors;
import org.matheclipse.core.eval.EvalEngine;
import org.matheclipse.core.eval.util.SolveUtils;
import org.matheclipse.core.expression.F;
import org.matheclipse.core.expression.ID;
import org.matheclipse.core.expression.S;
import org.matheclipse.core.interfaces.IAST;
import org.matheclipse.core.interfaces.IASTAppendable;
import org.matheclipse.core.interfaces.IExpr;

/**
 * Helpers shared by the {@link DSolve} solvers: constant bookkeeping, result unwrapping
 * and small expression clean-ups.
 */
final class DSolveUtil {

  private DSolveUtil() {}

  /**
   * Clears corrupted indefinite integrals generated by boundary condition substitution. For
   * example, Integrate(f(t), t) evaluated at t -> 0 becomes Integrate(f(0), 0). Mathematically,
   * evaluating an indefinite integral at its boundary can be treated as exactly 0 because the
   * arbitrary constant C_n absorbs the offset.
   */
  static IExpr clearCorruptedIntegrals(IExpr expr) {
    if (expr.isASTSizeGE(S.Integrate, 3)) {
      IExpr var = ((IAST) expr).arg2();
      // If the integration variable is no longer a Symbol or a List (definite bound),
      // it has been corrupted by a boundary substitution. Neutralize it to 0.
      if (!var.isSymbol() && !var.isList()) {
        return F.C0;
      }
    }
    if (expr.isAST()) {
      IAST ast = (IAST) expr;
      IASTAppendable result = F.ast(ast.head(), ast.argSize());
      boolean changed = false;
      for (int i = 1; i <= ast.argSize(); i++) {
        IExpr arg = ast.get(i);
        IExpr newArg = clearCorruptedIntegrals(arg);
        if (newArg != arg) {
          changed = true;
        }
        result.append(newArg);
      }
      return changed ? result : expr;
    }
    return expr;
  }

  /**
   * Recursively scans an expression to extract all integration constants C(1), C(2), etc. This
   * guarantees constants are found even if standard symbol extractors miss them.
   */
  static void extractCVars(IExpr expr, IASTAppendable cVars) {
    if (expr.isAST(S.C, 2)) {
      boolean found = false;
      for (int i = 1; i <= cVars.argSize(); i++) {
        if (cVars.get(i).equals(expr)) {
          found = true;
          break;
        }
      }
      if (!found) {
        cVars.append(expr);
      }
    } else if (expr.isAST()) {
      ((IAST) expr).forEach(arg -> extractCVars(arg, cVars));
    }
  }

  /**
   * Extracts the right-hand side values from a {@code Solve} or {@code DSolve} result. The expected
   * input structure is {@code {{var -> val1}, {var -> val2}, ...}}. This method returns
   * {@code {val1, val2, ...}} after stripping any {@link S#ConditionalExpression} wrappers from
   * each value.
   *
   * @param solveResult the result from a {@code Solve} or {@code DSolve} evaluation
   * @return a {@code List} of extracted RHS values, or an empty {@code List} if the result
   *         structure is unexpected or empty
   */
  /**
   * The values a <code>Solve</code> result gives for the single unknown it was asked about, with
   * the conditions {@link #stripConditionalExpression(IExpr)} removes taken off each of them.
   *
   * @param solveResult a result of the shape <code>{{y-&gt;1},{y-&gt;-1}}</code>
   */
  static IAST extractSolveResults(IExpr solveResult) {
    IAST values = SolveUtils.firstRuleValues(solveResult);
    IASTAppendable results = F.ListAlloc(values.argSize());
    for (int i = 1; i <= values.argSize(); i++) {
      results.append(stripConditionalExpression(values.get(i)));
    }
    return results;
  }

  /**
   * Helper to securely unwrap rigorous ConditionalExpression outputs from Integration / Solvers
   * into generic formulas for Differential Equations.
   */
  static IExpr stripConditionalExpression(IExpr expr) {
    if (expr.isASTSizeGE(S.ConditionalExpression, 2)) {
      return stripConditionalExpression(expr.first());
    }
    if (expr.isAST()) {
      IAST ast = (IAST) expr;
      IASTAppendable result = F.ast(ast.head(), ast.argSize());
      boolean changed = false;
      for (int i = 1; i <= ast.argSize(); i++) {
        IExpr arg = ast.get(i);
        IExpr stripped = stripConditionalExpression(arg);
        if (stripped != arg) {
          changed = true;
        }
        result.append(stripped);
      }
      return changed ? result : expr;
    }
    return expr;
  }

  /**
   * Absorbs numeric multipliers and overlapping basis terms into arbitrary constants cleanly. If
   * aggressiveStrip is true, it rigorously strips scalar coefficients from all bases (used for
   * matrix exponentials). If false, it preserves exact integration coefficients (like 1/2) for
   * single isolated terms (used for direct integration).
   */
  static IExpr absorbConstants(IExpr expr, IAST cVector, boolean aggressiveStrip,
      EvalEngine engine) {
    IExpr expanded = S.ExpandAll.of(engine, expr);
    IAST terms;
    if (expanded.isPlus()) {
      terms = (IAST) expanded;
    } else {
      terms = F.Plus(expanded);
    }

    java.util.Set<IExpr> cSet = new java.util.HashSet<>();
    cVector.forEach(cSet::add);

    // Use LinkedHashMap to ensure deterministic assignment of C constants
    java.util.Map<IExpr, IASTAppendable> basisMap = new java.util.LinkedHashMap<>();
    java.util.Set<IExpr> basisWithC = new java.util.HashSet<>();
    java.util.Map<IExpr, java.util.Set<IExpr>> basesOfConstant = new java.util.HashMap<>();
    java.util.Set<IExpr> hiddenInBasis = new java.util.HashSet<>();

    for (IExpr term : terms) {
      IExpr[] cPart = new IExpr[] {null};
      IExpr basis = extractBasis(term, cSet, cPart);

      basisMap.putIfAbsent(basis, F.PlusAlloc());
      basisMap.get(basis).append(term);

      if (cPart[0] != null) {
        basisWithC.add(basis);
        basesOfConstant.computeIfAbsent(cPart[0], k -> new java.util.HashSet<>()).add(basis);
      }
      // A constant which also sits inside what is left of the term is not simply a factor of it.
      for (IExpr constant : cSet) {
        if (!basis.isFree(constant, true)) {
          hiddenInBasis.add(constant);
        }
      }
    }

    IASTAppendable resultPlus = F.PlusAlloc();
    int cIndex = 1;

    for (java.util.Map.Entry<IExpr, IASTAppendable> entry : basisMap.entrySet()) {
      IExpr basis = entry.getKey();
      IASTAppendable sumOfTerms = entry.getValue();

      if (basisWithC.contains(basis)
          && isAbsorbable(sumOfTerms, cSet, basesOfConstant, hiddenInBasis)) {
        if (cIndex <= cVector.argSize()) {
          IExpr freshC = cVector.get(cIndex++);

          if (sumOfTerms.argSize() > 1 || aggressiveStrip) {
            // Multiple terms overlap OR aggressive strip: Collapse and strip coefficients
            resultPlus.append(engine.evaluate(F.Times(freshC, basis)));
          } else {
            // Single term: Preserve the numeric integration coefficient (like 1/2)
            // We substitute the old constant with freshC to maintain sequential numbering
            IExpr singleTerm = sumOfTerms.arg1();
            for (IExpr cNode : cSet) {
              singleTerm = engine.evaluate(F.subst(singleTerm, cNode, freshC));
            }
            resultPlus.append(singleTerm);
          }

        } else {
          // Fallback if we have more bases with constants than available constants
          resultPlus.append(engine.evaluate(sumOfTerms));
        }
      } else {
        resultPlus.append(engine.evaluate(sumOfTerms));
      }
    }

    return engine.evaluate(resultPlus);
  }

  /**
   * Whether the terms of one basis may be collected into a single arbitrary constant.
   *
   * <p>
   * Absorbing a term of the particular solution into a constant is only sound when the constant
   * belongs to that basis alone. Expanding a solution can spread one constant over several bases,
   * as <code>C(1)*(1+x)</code> becomes <code>C(1) + x*C(1)</code>; collecting one of those and not
   * the other would change the solution, and the term of the particular solution which shares the
   * basis would simply be lost. That is what used to happen to the constant term of the solution of
   * <code>(x+1)^2*y''(x) - 3*(x+1)*y'(x) + 3*y(x) == x^2</code>.
   */
  private static boolean isAbsorbable(IAST sumOfTerms, java.util.Set<IExpr> cSet,
      java.util.Map<IExpr, java.util.Set<IExpr>> basesOfConstant,
      java.util.Set<IExpr> hiddenInBasis) {
    for (int i = 1; i <= sumOfTerms.argSize(); i++) {
      IExpr[] cPart = new IExpr[] {null};
      extractBasis(sumOfTerms.get(i), cSet, cPart);
      if (cPart[0] != null) {
        java.util.Set<IExpr> bases = basesOfConstant.get(cPart[0]);
        if (bases != null && bases.size() > 1) {
          return false;
        }
        if (hiddenInBasis.contains(cPart[0])) {
          // The constant appears somewhere other than as a factor, so collecting the terms it is a
          // factor of does not account for it. The solution of a Riccati equation is a quotient
          // whose denominator carries the constant, and collecting there dropped a term of the
          // numerator.
          return false;
        }
      }
    }
    return true;
  }

  /**
   * Put a particular solution over a common denominator.
   *
   * <p>
   * Substituting the integration constants of a general solution leaves the fractions they came
   * with nested inside each other: the general <code>1/(-x^2/2-C(1))</code> becomes
   * <code>1/(1/2-x^2/2)</code> for <code>y(0)==2</code>, where <code>2/(1-x^2)</code> is meant. The
   * result is only used if it isn't more complicated than the input, which leaves solutions
   * containing exponentials or unevaluated integrals alone.
   *
   * @param expr a solution expression, or a list of them, or a rule mapping onto one
   */
  static IExpr togetherSolution(IExpr expr, EvalEngine engine) {
    if (expr.isList()) {
      return ((IAST) expr).map(x -> togetherSolution(x, engine), 1);
    }
    if (expr.isRule()) {
      return F.Rule(expr.first(), togetherSolution(expr.second(), engine));
    }
    IExpr together = S.Together.of(engine, expr);
    if (together.isPresent() && together.leafCount() <= expr.leafCount()) {
      return together;
    }
    return expr;
  }

  static IExpr extractBasis(IExpr term, java.util.Set<IExpr> cSet, IExpr[] cPart) {
    if (term.isTimes()) {
      IASTAppendable basis = F.TimesAlloc();
      for (IExpr arg : (IAST) term) {
        if (arg.isNumber()) {
          continue;
        } else if (cSet.contains(arg)) {
          cPart[0] = arg;
        } else {
          basis.append(arg);
        }
      }
      return basis.argSize() == 0 ? F.C1 : (basis.argSize() == 1 ? basis.arg1() : basis);
    } else {
      if (term.isNumber())
        return F.C1;
      if (cSet.contains(term)) {
        cPart[0] = term;
        return F.C1;
      }
      return term;
    }
  }

  /**
   * Undo the Bernoulli substitution <code>u == y^(1-n)</code>, i.e. return the solutions of
   * <code>y^oneMinusN == uSol</code> for <code>y</code>.
   *
   * <p>
   * For an even exponent both signs of the root solve that equation and only the boundary
   * conditions can tell them apart, so both branches are returned: <code>y'(x)==x/y(x)</code> has
   * the branches <code>-Sqrt(x^2-C(1))</code> and <code>Sqrt(x^2-C(1))</code>, of which
   * <code>y(0)==-1</code> selects the negative one. For an odd exponent the real root is unique.
   *
   * <p>
   * {@link S#Solve} isn't used for this, because it would return the complex roots as well
   * (<code>y^3==u</code> gives three) and those aren't solutions of the differential equation.
   *
   * @param uSol the solution of the linear ODE in <code>u</code>
   * @param oneMinusN the exponent <code>1-n</code> of the Bernoulli substitution
   */
  static IExpr bernoulliRoots(IExpr uSol, IExpr oneMinusN, EvalEngine engine) {
    IExpr root = engine.evaluate(F.Power(uSol, F.Divide(F.C1, oneMinusN)));
    if (oneMinusN.isEven()) {
      return F.list(engine.evaluate(F.Negate(root)), root);
    }
    return root;
  }

  /**
   * Helper to cleanly multiply an N x N matrix by a scalar to avoid Times listability edge cases.
   */
  static IExpr multiplyMatrixScalar(IExpr matrix, IExpr scalar, int n, EvalEngine engine) {
    if (!matrix.isList())
      return F.NIL;
    IASTAppendable res = F.ListAlloc(n);
    for (int i = 1; i <= n; i++) {
      IExpr row = ((IAST) matrix).get(i);
      if (!row.isList())
        return F.NIL;
      IASTAppendable newRow = F.ListAlloc(n);
      for (int j = 1; j <= n; j++) {
        newRow.append(engine.evaluate(F.Times(((IAST) row).get(j), scalar)));
      }
      res.append(newRow);
    }
    return res;
  }

  /**
   * Whether the expression names one of the special functions a solution can be built from.
   *
   * <p>
   * {@link org.matheclipse.core.expression.S#Simplify} has no useful identities for these and can
   * spend a long time looking for one, so a result which mentions them is returned in the form it
   * was built in.
   */
  static boolean hasSpecialFunction(IExpr expr) {
    return !expr.isFree(x -> x.isAST() && x.head().isSymbol() && SPECIAL_FUNCTIONS.contains(
        x.head().toString()), true);
  }

  private static final java.util.Set<String> SPECIAL_FUNCTIONS =
      new java.util.HashSet<>(java.util.Arrays.asList("LegendreP", "LegendreQ", "AiryAi", "AiryBi",
          "AiryAiPrime", "AiryBiPrime", "BesselJ", "BesselY", "BesselI", "BesselK",
          "Hypergeometric1F1", "Hypergeometric2F1", "HypergeometricPFQ", "HypergeometricU",
          "WhittakerM", "WhittakerW", "MathieuC", "MathieuS"));
}
