  private static void assertClose(IExpr actual, double re, double im, String what) {
    double magnitude = Math.hypot(re, im);
    if (!Double.isFinite(magnitude) || magnitude > 1.0e290 || magnitude < 1.0e-300) {
      return; // not representable as a double either way
    }
    double actualRe;
    double actualIm;
    if (actual instanceof IComplexNum) {
      actualRe = ((IComplexNum) actual).reDoubleValue();
      actualIm = ((IComplexNum) actual).imDoubleValue();
    } else if (actual.isReal()) {
      actualRe = actual.evalf();
      actualIm = 0.0;
    } else {
      throw new AssertionError(what + " did not evaluate numerically: " + actual);
    }
    double error = Math.hypot(actualRe - re, actualIm - im) / magnitude;
    assertTrue(error < MAX_ERROR, what + ": expected (" + re + ", " + im + ") but was (" + actualRe
        + ", " + actualIm + ") - relative error " + error);
  }

