package org.matheclipse.core.sympy.combinatorics;

import java.math.BigInteger;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;
import org.matheclipse.core.expression.F;
import org.matheclipse.core.interfaces.IInteger;
import org.matheclipse.core.sympy.exception.ValueError;

/**
 * A permutation group defined by a list of generators. Follows the API of the class
 * <code>PermutationGroup</code> in
 * <a href="https://github.com/sympy/sympy/blob/master/sympy/combinatorics/perm_groups.py">sympy/combinatorics/perm_groups.py</a>
 *
 * <p>
 * All permutations are in the 0-based array form of {@link Permutations}; the product
 * <code>a*b</code> applies <code>a</code> first. The order, the membership test and the
 * enumeration of the elements are based on a base and strong generating set computed with the
 * deterministic Schreier-Sims algorithm.
 */
public class PermGroups {

  private final int degree;

  private final List<int[]> generators;

  /** The base <code>b(0), b(1),...</code> of the stabilizer chain */
  private List<Integer> base;

  /** The generators of the subgroup which fixes the base points <code>b(0),...,b(i-1)</code> */
  private List<List<int[]>> strongGens;

  /** <code>transversals.get(i)[p]</code> maps the base point <code>b(i)</code> to the point p */
  private List<int[][]> transversals;

  /** The basic orbits in the order of their enumeration */
  private List<int[]> basicOrbits;

  /**
   * Create the group which is generated by the <code>generators</code>.
   *
   * @param generators the generators in array form; shorter generators are padded with fixed
   *        points
   * @param degree the number of points on which the group acts
   */
  public PermGroups(List<int[]> generators, int degree) {
    this.degree = degree;
    this.generators = new ArrayList<int[]>(generators.size());
    for (int i = 0; i < generators.size(); i++) {
      int[] g = generators.get(i);
      if (g.length > degree) {
        throw new ValueError("The generator is greater than the degree " + degree);
      }
      this.generators.add(Permutations.resize(g, degree).clone());
    }
  }

  /**
   * Create the group which is generated by the <code>generators</code>. The degree is the maximum
   * size of the generators.
   */
  public PermGroups(List<int[]> generators) {
    this(generators, maxDegree(generators));
  }

  private static int maxDegree(List<int[]> generators) {
    int degree = 0;
    for (int i = 0; i < generators.size(); i++) {
      degree = Math.max(degree, generators.get(i).length);
    }
    return degree;
  }

  /** Returns the size of the permutations in the group. */
  public int degree() {
    return degree;
  }

  /** Returns the generators of the group. */
  public List<int[]> generators() {
    return Collections.unmodifiableList(generators);
  }

  /**
   * Compute the orbit of <code>alpha</code> as the set of images of <code>alpha</code> under the
   * group.
   *
   * @return the sorted points of the orbit
   */
  public int[] orbit(int alpha) {
    // >>> a = Permutation([1, 2, 0, 4, 5, 6, 3])
    // >>> G = PermutationGroup([a])
    // >>> G.orbit(0)
    // {0, 1, 2}
    int[] orbit = orbit(generators, alpha, degree, null);
    Arrays.sort(orbit);
    return orbit;
  }

  /**
   * Compute the orbits of the group.
   *
   * @return the list of sorted orbits, sorted by their smallest point
   */
  public List<int[]> orbits() {
    // >>> a = Permutation(1, 5)(2, 3)(4, 0, 6)
    // >>> b = Permutation(1, 5)(3, 4)(2, 6, 0)
    // >>> G = PermutationGroup([a, b])
    // >>> G.orbits()
    // [{0, 2, 3, 4, 6}, {1, 5}]
    List<int[]> result = new ArrayList<int[]>();
    boolean[] seen = new boolean[degree];
    for (int i = 0; i < degree; i++) {
      if (!seen[i]) {
        int[] orbit = orbit(i);
        for (int j = 0; j < orbit.length; j++) {
          seen[orbit[j]] = true;
        }
        result.add(orbit);
      }
    }
    return result;
  }

  /**
   * Test if the group is transitive, i.e. has only one orbit.
   */
  public boolean isTransitive() {
    return degree == 0 || orbit(0).length == degree;
  }

  /**
   * Test if the group is abelian.
   */
  public boolean isAbelian() {
    for (int i = 0; i < generators.size(); i++) {
      for (int j = i + 1; j < generators.size(); j++) {
        int[] a = generators.get(i);
        int[] b = generators.get(j);
        if (!Arrays.equals(Permutations.mul(a, b), Permutations.mul(b, a))) {
          return false;
        }
      }
    }
    return true;
  }

  /**
   * Compute the orbit of alpha in the order of the enumeration.
   *
   * @param transversal if not <code>null</code> the permutation which maps <code>alpha</code> to
   *        the point <code>p</code> is stored at index <code>p</code>
   */
  private static int[] orbit(List<int[]> gens, int alpha, int degree, int[][] transversal) {
    int[] orbit = new int[degree];
    boolean[] used = new boolean[degree];
    int size = 0;
    orbit[size++] = alpha;
    used[alpha] = true;
    if (transversal != null) {
      transversal[alpha] = Permutations.identity(degree);
    }
    for (int i = 0; i < size; i++) {
      final int point = orbit[i];
      for (int j = 0; j < gens.size(); j++) {
        int[] gen = gens.get(j);
        int image = gen[point];
        if (!used[image]) {
          used[image] = true;
          orbit[size++] = image;
          if (transversal != null) {
            transversal[image] = Permutations.mul(transversal[point], gen);
          }
        }
      }
    }
    return Arrays.copyOf(orbit, size);
  }

  /**
   * Schreier-Sims algorithm. It computes a base and the generators of the basic stabilizers.
   *
   * @param initialBase the points which should be used as first base points or <code>null</code>
   */
  private void schreierSims(int[] initialBase) {
    base = new ArrayList<Integer>();
    strongGens = new ArrayList<List<int[]>>();
    transversals = new ArrayList<int[][]>();
    basicOrbits = new ArrayList<int[]>();
    if (initialBase != null) {
      for (int i = 0; i < initialBase.length; i++) {
        if (!base.contains(initialBase[i])) {
          base.add(initialBase[i]);
        }
      }
    }
    List<int[]> gens = new ArrayList<int[]>();
    for (int i = 0; i < generators.size(); i++) {
      int[] g = generators.get(i);
      if (!Permutations.isIdentity(g)) {
        gens.add(g);
        extendBase(g);
      }
    }
    for (int i = 0; i < base.size(); i++) {
      strongGens.add(new ArrayList<int[]>());
      transversals.add(null);
      basicOrbits.add(null);
    }
    for (int k = 0; k < gens.size(); k++) {
      addStrongGenerator(gens.get(k), 0);
    }
    for (int i = 0; i < base.size(); i++) {
      updateLevel(i);
    }

    int i = base.size() - 1;
    while (i >= 0) {
      boolean restart = false;
      final int[] orbit = basicOrbits.get(i);
      final int[][] transversal = transversals.get(i);
      final List<int[]> levelGens = new ArrayList<int[]>(strongGens.get(i));
      search: for (int o = 0; o < orbit.length; o++) {
        final int beta = orbit[o];
        final int[] uBeta = transversal[beta];
        for (int k = 0; k < levelGens.size(); k++) {
          final int[] gen = levelGens.get(k);
          // the Schreier generator u(beta) * gen * u(beta^gen)^(-1)
          int[] schreierGen = Permutations.mul(Permutations.mul(uBeta, gen),
              Permutations.inverse(transversal[gen[beta]]));
          if (Permutations.isIdentity(schreierGen)) {
            continue;
          }
          int[] level = new int[1];
          int[] h = strip(schreierGen, i + 1, level);
          if (!Permutations.isIdentity(h)) {
            int j = level[0];
            if (j == base.size()) {
              extendBase(h);
              strongGens.add(new ArrayList<int[]>());
              transversals.add(null);
              basicOrbits.add(null);
            }
            for (int l = i + 1; l <= j; l++) {
              strongGens.get(l).add(h);
              updateLevel(l);
            }
            i = j;
            restart = true;
            break search;
          }
        }
      }
      if (!restart) {
        i--;
      }
    }
  }

  /** Add a new base point which is moved by the permutation. */
  private void extendBase(int[] g) {
    for (int i = 0; i < base.size(); i++) {
      if (g[base.get(i)] != base.get(i)) {
        return;
      }
    }
    for (int p = 0; p < g.length; p++) {
      if (g[p] != p) {
        base.add(p);
        return;
      }
    }
  }

  /** Add the generator to all levels, where the generator fixes the previous base points. */
  private void addStrongGenerator(int[] g, int fromLevel) {
    for (int l = fromLevel; l < base.size(); l++) {
      strongGens.get(l).add(g);
      if (g[base.get(l)] != base.get(l)) {
        break;
      }
    }
  }

  private void updateLevel(int level) {
    int[][] transversal = new int[degree][];
    basicOrbits.set(level, orbit(strongGens.get(level), base.get(level), degree, transversal));
    transversals.set(level, transversal);
  }

  /**
   * Attempt to decompose the permutation <code>g</code> using the transversals starting at the
   * level <code>fromLevel</code>.
   *
   * @param level the level at which the decomposition stops is returned at index 0
   * @return the residue; the identity if <code>g</code> could be decomposed completely
   */
  private int[] strip(int[] g, int fromLevel, int[] level) {
    int[] h = g;
    for (int l = fromLevel; l < base.size(); l++) {
      int beta = h[base.get(l)];
      int[] u = transversals.get(l)[beta];
      if (u == null) {
        level[0] = l;
        return h;
      }
      h = Permutations.mul(h, Permutations.inverse(u));
    }
    level[0] = base.size();
    return h;
  }

  private void ensureStabilizerChain() {
    if (base == null) {
      schreierSims(null);
    }
  }

  /**
   * Return a base from the Schreier-Sims algorithm.
   */
  public int[] base() {
    // >>> G = PermutationGroup([Permutation(0, 1, 3)(2, 4)])
    // >>> G.base
    // [0, 2]
    ensureStabilizerChain();
    int[] result = new int[base.size()];
    for (int i = 0; i < result.length; i++) {
      result[i] = base.get(i);
    }
    return result;
  }

  /**
   * Return a strong generating set from the Schreier-Sims algorithm.
   */
  public List<int[]> strongGens() {
    ensureStabilizerChain();
    List<int[]> result = new ArrayList<int[]>();
    for (int l = 0; l < strongGens.size(); l++) {
      for (int[] g : strongGens.get(l)) {
        boolean found = false;
        for (int[] r : result) {
          if (Arrays.equals(r, g)) {
            found = true;
            break;
          }
        }
        if (!found) {
          result.add(g);
        }
      }
    }
    return result;
  }

  /**
   * Return the order of the group: the number of permutations that can be generated from elements
   * of the group.
   */
  public IInteger order() {
    // >>> a = Permutation([1, 0, 2])
    // >>> G = PermutationGroup([a])
    // >>> G.order()
    // 2
    ensureStabilizerChain();
    BigInteger order = BigInteger.ONE;
    for (int i = 0; i < basicOrbits.size(); i++) {
      order = order.multiply(BigInteger.valueOf(basicOrbits.get(i).length));
    }
    return F.ZZ(order);
  }

  /**
   * Test if the permutation is an element of the group.
   */
  public boolean contains(int[] g) {
    // >>> a = Permutation(1, 2)
    // >>> b = Permutation(2, 3, 1)
    // >>> G = PermutationGroup(a, b, degree=5)
    // >>> G.contains(G[0]) # trivial check
    // True
    // >>> elem = Permutation([[2, 3]], size=5)
    // >>> G.contains(elem)
    // True
    if (g.length > degree) {
      for (int i = degree; i < g.length; i++) {
        if (g[i] != i) {
          return false;
        }
      }
      g = Arrays.copyOf(g, degree);
    }
    g = Permutations.resize(g, degree);
    ensureStabilizerChain();
    return Permutations.isIdentity(strip(g, 0, new int[1]));
  }

  /**
   * Returns all the elements of the permutation group sorted in lexicographic order.
   *
   * @param limit the maximum number of elements
   * @return <code>null</code> if the order of the group is greater than <code>limit</code>
   */
  public List<int[]> elements(int limit) {
    // >>> p = PermutationGroup(Permutation(1, 3), Permutation(1, 2))
    // >>> p.elements
    // {(1 2 3), (1 3 2), (1 3), (2 3), (3), (3)(1 2)}
    ensureStabilizerChain();
    if (order().compareTo(F.ZZ(limit)) > 0) {
      return null;
    }
    List<int[]> elements = new ArrayList<int[]>();
    elements.add(Permutations.identity(degree));
    // every element is a unique product u(k-1)*...*u(1)*u(0) of transversal elements
    for (int l = base.size() - 1; l >= 0; l--) {
      final int[] orbit = basicOrbits.get(l);
      final int[][] transversal = transversals.get(l);
      List<int[]> next = new ArrayList<int[]>(elements.size() * orbit.length);
      for (int[] element : elements) {
        for (int o = 0; o < orbit.length; o++) {
          next.add(Permutations.mul(element, transversal[orbit[o]]));
        }
      }
      elements = next;
    }
    Collections.sort(elements, Arrays::compare);
    return elements;
  }

  /**
   * Return the stabilizer subgroup of <code>alpha</code>: the subgroup of all elements which fix
   * the point <code>alpha</code>.
   */
  public PermGroups stabilizer(int alpha) {
    // >>> G = DihedralGroup(6)
    // >>> G.stabilizer(5)
    // PermutationGroup([
    // (5)(0 4)(1 3)])
    PermGroups group = new PermGroups(generators, degree);
    group.schreierSims(new int[] {alpha});
    List<int[]> gens = new ArrayList<int[]>();
    if (group.strongGens.size() > 1) {
      for (int[] g : group.strongGens.get(1)) {
        boolean found = false;
        for (int[] r : gens) {
          if (Arrays.equals(r, g)) {
            found = true;
            break;
          }
        }
        if (!found) {
          gens.add(g);
        }
      }
    }
    if (gens.isEmpty()) {
      gens.add(Permutations.identity(degree));
    }
    return new PermGroups(gens, degree);
  }

  /**
   * Test if all the elements of this group are elements of the <code>other</code> group.
   */
  public boolean isSubgroup(PermGroups other) {
    for (int i = 0; i < generators.size(); i++) {
      if (!other.contains(generators.get(i))) {
        return false;
      }
    }
    return true;
  }
}
