  private static void assertClose(double expected, double actual, String what) {
    if (Double.isNaN(expected)) {
      return;
    }
    assertFalse(Double.isNaN(actual), what + ": unexpectedly withdrawn");
    double error = Math.abs((actual - expected) / expected);
    assertTrue(error < MAX_ERROR,
        what + ": expected " + expected + " but was " + actual + " (relative error " + error + ")");
  }

  @Test
  public void testAgainstReferenceValues() {
    for (double[] row : REFERENCE) {
      double v = row[0];
      double x = row[1];
      assertTrue(BesselIK.isSupported(v, x), "reference point outside the domain");
      assertClose(row[2], BesselIK.besselI(v, x), "BesselI(" + v + ", " + x + ")");
      assertClose(row[3], BesselIK.besselK(v, x), "BesselK(" + v + ", " + x + ")");
    }
  }

  /** K is even in the order - exactly, not approximately. */
  @Test
  public void testKIsEvenInOrder() {
    for (double v : new double[] {0.25, 0.5, 1.0, 2.5, 7.0, 10.5}) {
      for (double x : new double[] {0.01, 0.5, 2.0, 10.0, 100.0}) {
        assertEquals(BesselIK.besselK(v, x), BesselIK.besselK(-v, x), 0.0,
            "K(-" + v + ", " + x + ")");
      }
    }
  }

  /** At an integer order I is even too, which the reflection has to take exactly. */
  @Test
  public void testIIsEvenAtIntegerOrder() {
    for (int n = 0; n <= 6; n++) {
      for (double x : new double[] {1.0e-6, 0.01, 0.5, 2.0, 10.0}) {
        double positive = BesselIK.besselI(n, x);
        assertEquals(positive, BesselIK.besselI(-n, x), Math.abs(positive) * 1.0e-15,
            "I(-" + n + ", " + x + ")");
      }
    }
  }

  /**
   * The Wronskian <code>I_(v+1)*K_v + I_v*K_(v+1) = 1/x</code> ties the two recurrences together
   * without needing an external reference.
   */
  @Test
  public void testWronskian() {
    for (double v : new double[] {0.0, 0.25, 0.5, 1.0, 2.3, 5.0, 11.75}) {
      for (double x : new double[] {0.01, 0.5, 1.0, 1.9999, 2.0, 3.7, 20.0, 90.0}) {
        double expected = 1.0 / x;
        double actual = BesselIK.besselI(v + 1.0, x) * BesselIK.besselK(v, x)
            + BesselIK.besselI(v, x) * BesselIK.besselK(v + 1.0, x);
        assertEquals(expected, actual, Math.abs(expected) * 1.0e-11,
            "Wronskian v=" + v + " x=" + x);
      }
    }
  }

  /** Half-odd-integer orders have closed forms, which pin the normalization. */
  @Test
  public void testClosedForms() {
    double x = 1.7;
    double scale = Math.sqrt(2.0 / (Math.PI * x));
    assertEquals(scale * Math.sinh(x), BesselIK.besselI(0.5, x), 1.0e-14);
    assertEquals(scale * Math.cosh(x), BesselIK.besselI(-0.5, x), 1.0e-14);
    assertEquals(Math.sqrt(Math.PI / (2.0 * x)) * Math.exp(-x), BesselIK.besselK(0.5, x), 1.0e-15);
  }

  @Test
  public void testDomainBoundaries() {
    assertTrue(BesselIK.isSupported(1.3, 700.0));
    assertFalse(BesselIK.isSupported(1.3, 700.1));
    assertFalse(BesselIK.isSupported(1.3, 0.0));
    assertFalse(BesselIK.isSupported(1.3, -1.0));
    assertFalse(BesselIK.isSupported(2000.0, 1.0));
  }
