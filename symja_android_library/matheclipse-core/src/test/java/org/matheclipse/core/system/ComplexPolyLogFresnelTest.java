  private static void assertClose(IExpr actual, double expectedRe, double expectedIm, String what) {
    double actualRe;
    double actualIm;
    if (actual instanceof IComplexNum) {
      actualRe = ((IComplexNum) actual).reDoubleValue();
      actualIm = ((IComplexNum) actual).imDoubleValue();
    } else if (actual.isReal()) {
      actualRe = actual.evalf();
      actualIm = 0.0;
    } else {
      throw new AssertionError(what + " did not evaluate numerically: " + actual);
    }
    double scale = Math.max(Math.hypot(expectedRe, expectedIm), 1.0e-300);
    double error = Math.hypot(actualRe - expectedRe, actualIm - expectedIm) / scale;
    assertTrue(error < MAX_ERROR, what + ": expected (" + expectedRe + ", " + expectedIm
        + ") but was (" + actualRe + ", " + actualIm + ") - relative error " + error);
  }

  @Test
  public void testPolyLogAgainstWMA() {
    for (double[] row : POLYLOG2) {
      IComplexNum z = F.complexNum(row[0], row[1]);
      assertClose(F.complexNum(2.0, 0.0).polyLog(z), row[2], row[3],
          "PolyLog(2, " + row[0] + "+" + row[1] + "i)");
    }
  }

  /**
   * The closed forms at order 1, 0 and -1 hold for a complex argument too, and none of them goes
   * through the series the implementation otherwise sums.
   */
  @Test
  public void testPolyLogClosedForms() {
    for (double[] row : POLYLOG2) {
      org.hipparchus.complex.Complex z = new org.hipparchus.complex.Complex(row[0], row[1]);
      org.hipparchus.complex.Complex expected1 =
          org.hipparchus.complex.Complex.ONE.subtract(z).log().negate();
      assertClose(F.complexNum(1.0, 0.0).polyLog(F.complexNum(row[0], row[1])), expected1.getReal(),
          expected1.getImaginary(), "PolyLog(1, z)");
      org.hipparchus.complex.Complex expected0 =
          z.divide(org.hipparchus.complex.Complex.ONE.subtract(z));
      assertClose(F.complexNum(0.0, 0.0).polyLog(F.complexNum(row[0], row[1])), expected0.getReal(),
          expected0.getImaginary(), "PolyLog(0, z)");
    }
  }

  @Test
  public void testFresnel() {
    for (double[] row : FRESNEL) {
      IComplexNum z = F.complexNum(row[0], row[1]);
      assertClose(z.fresnelC(), row[2], row[3], "FresnelC(" + row[0] + "+" + row[1] + "i)");
      assertClose(z.fresnelS(), row[4], row[5], "FresnelS(" + row[0] + "+" + row[1] + "i)");
    }
  }

  /**
   * Both Fresnel integrals are odd, which the series has to reproduce independently for
   * <code>z</code> and <code>-z</code>.
   */
  @Test
  public void testFresnelOddSymmetry() {
    for (double[] row : FRESNEL) {
      IExpr positive = F.complexNum(row[0], row[1]).fresnelC();
      IExpr negative = F.complexNum(-row[0], -row[1]).fresnelC();
      assertClose(negative, -((IComplexNum) positive).reDoubleValue(),
          -((IComplexNum) positive).imDoubleValue(), "FresnelC oddness at " + row[0]);
    }
  }
