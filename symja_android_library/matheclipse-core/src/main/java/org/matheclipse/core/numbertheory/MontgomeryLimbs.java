  /** @param n an odd number which {@link #fits(BigInteger)} */
  MontgomeryLimbs(BigInteger n) {
    modulus = n;
    k = Math.max(2, (n.bitLength() + 63) >>> 6);
    this.n = toLimbs(n, k);
    n0 = this.n[0];
    n1 = this.n[1];
    n2 = k > 2 ? this.n[2] : 0L;
    n3 = k > 3 ? this.n[3] : 0L;
    // Newton iteration for n0^(-1) mod 2^64; n0 is its own inverse modulo 2^3
    long inverse = n0;
    for (int i = 0; i < 5; i++) {
      inverse *= 2 - n0 * inverse;
    }
    nInverse = -inverse;
    BigInteger r = BigInteger.ONE.shiftLeft(64 * k).mod(n);
    one = toLimbs(r, k);
    r2 = toLimbs(r.multiply(r).mod(n), k);
    t = new long[k + 2];
  }

  /** Test if {@link MontgomeryLimbs} works modulo <code>n</code>: odd and greater than 1. */
  static boolean fits(BigInteger n) {
    return n.testBit(0) && n.compareTo(BigInteger.ONE) > 0;
  }

  long[] newElement() {
    return new long[k];
  }

  /** The unsigned high 64 bits of the 128-bit product <code>a*b</code>. */
  private static long multiplyHighUnsigned(long a, long b) {
    return Math.multiplyHigh(a, b) + ((a >> 63) & b) + ((b >> 63) & a);
  }

  /** The carry of the unsigned sum <code>s = a + b</code>. */
  private static long carry(long a, long b, long s) {
    return ((a & b) | ((a | b) & ~s)) >>> 63;
  }

  /** The borrow of the unsigned difference <code>d = x - y</code>. */
  private static long borrow(long x, long y, long d) {
    return ((~x & y) | (~(x ^ y) & d)) >>> 63;
  }

  /**
   * <code>out = a*b/R mod n</code>, the Montgomery product of <code>a, b &lt; n</code>;
   * <code>out</code> may be an operand.
   */
  void mul(long[] a, long[] b, long[] out) {
    switch (k) {
      case 2:
        mul2(a, b, out);
        break;
      case 3:
        mul3(a, b, out);
        break;
      case 4:
        mul4(a, b, out);
        break;
      default:
        mulGeneric(a, b, out);
        break;
    }
  }

