package org.matheclipse.tools;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

/**
 * Generates the unrolled 2, 3 and 4 limb methods of
 * <code>org.matheclipse.core.numbertheory.MontgomeryLimbs</code>: the Montgomery multiplication
 * (CIOS), the squaring (SOS) and the branch-free modular addition and subtraction.
 *
 * <p>
 * The generated code replaces the region between {@link #BEGIN} and {@link #END} in
 * <code>MontgomeryLimbs.java</code>. Run it from the <code>symja_android_library</code> directory,
 * or pass the path of <code>MontgomeryLimbs.java</code> as the only argument.
 */
public class MontgomeryLimbsGenerator {

  static final String BEGIN =
      "  // BEGIN GENERATED by org.matheclipse.tools.MontgomeryLimbsGenerator - do not edit";

  static final String END = "  // END GENERATED";

  private static final String DEFAULT_PATH =
      "matheclipse-core/src/main/java/org/matheclipse/core/numbertheory/MontgomeryLimbs.java";

  private final StringBuilder out = new StringBuilder();

  private void w(String line) {
    out.append(line).append('\n');
  }

  /** The unrolled Montgomery multiplication (coarsely integrated operand scanning). */
  private void mul(int k) {
    w("");
    w("  /** {@link #mul(long[], long[], long[])} unrolled for " + k + " limbs. */");
    w("  private void mul" + k + "(long[] a, long[] b, long[] out) {");
    for (int j = 0; j < k; j++) {
      w("    final long a" + j + " = a[" + j + "];");
    }
    for (int j = 0; j < k; j++) {
      w("    final long b" + j + " = b[" + j + "];");
    }
    modulusLimbs(k);
    w("    long l;");
    w("    long h;");
    w("    long s;");
    w("    long s2;");
    w("    long c;");
    w("    long m;");
    for (int j = 0; j < k + 2; j++) {
      w("    long t" + j + ";");
    }
    for (int i = 0; i < k; i++) {
      w("");
      w("    // t = t + a * b" + i);
      if (i == 0) {
        w("    t0 = a0 * b0;");
        w("    c = multiplyHighUnsigned(a0, b0);");
        for (int j = 1; j < k; j++) {
          w("    l = a" + j + " * b0;");
          w("    h = multiplyHighUnsigned(a" + j + ", b0);");
          w("    s = l + c;");
          w("    h += carry(l, c, s);");
          w("    t" + j + " = s;");
          w("    c = h;");
        }
        w("    t" + k + " = c;");
        w("    t" + (k + 1) + " = 0;");
      } else {
        w("    l = a0 * b" + i + ";");
        w("    h = multiplyHighUnsigned(a0, b" + i + ");");
        w("    s = t0 + l;");
        w("    h += carry(t0, l, s);");
        w("    t0 = s;");
        w("    c = h;");
        for (int j = 1; j < k; j++) {
          multiplyAccumulate("a" + j, "b" + i, "t" + j, "t" + j);
        }
        w("    s = t" + k + " + c;");
        w("    t" + (k + 1) + " = carry(t" + k + ", c, s);");
        w("    t" + k + " = s;");
      }
      w("    // t = (t + m * n) / 2^64");
      w("    m = t0 * nInverse;");
      w("    l = m * n0;");
      w("    h = multiplyHighUnsigned(m, n0);");
      w("    s = t0 + l;");
      w("    c = h + carry(t0, l, s);");
      for (int j = 1; j < k; j++) {
        multiplyAccumulate("m", "n" + j, "t" + j, "t" + (j - 1));
      }
      w("    s = t" + k + " + c;");
      w("    t" + (k - 1) + " = s;");
      w("    t" + k + " = t" + (k + 1) + " + carry(t" + k + ", c, s);");
    }
    w("");
    finalSubtraction(k, 0, "t" + k);
    w("  }");
  }

  /** <code>(c, target) = source + x*y + c</code> */
  private void multiplyAccumulate(String x, String y, String source, String target) {
    w("    l = " + x + " * " + y + ";");
    w("    h = multiplyHighUnsigned(" + x + ", " + y + ");");
    w("    s = " + source + " + l;");
    w("    h += carry(" + source + ", l, s);");
    w("    s2 = s + c;");
    w("    h += carry(s, c, s2);");
    w("    " + target + " = s2;");
    w("    c = h;");
  }

  /** <code>out = t[offset..offset+k-1] (+ high*2^(64k))</code> reduced once below n. */
  private void finalSubtraction(int k, int offset, String high) {
    w("    // t < 2n: subtract n once if t >= n");
    w("    boolean subtract;");
    w("    if (" + high + " != 0) {");
    w("      subtract = true;");
    for (int j = k - 1; j > 0; j--) {
      w("    } else if (t" + (offset + j) + " != n" + j + ") {");
      w("      subtract = Long.compareUnsigned(t" + (offset + j) + ", n" + j + ") > 0;");
    }
    w("    } else {");
    w("      subtract = Long.compareUnsigned(t" + offset + ", n0) >= 0;");
    w("    }");
    w("    if (subtract) {");
    w("      long borrow = Long.compareUnsigned(t" + offset + ", n0) < 0 ? 1L : 0L;");
    w("      out[0] = t" + offset + " - n0;");
    for (int j = 1; j < k; j++) {
      w("      out[" + j + "] = t" + (offset + j) + " - n" + j + " - borrow;");
      if (j < k - 1) {
        w("      borrow =");
        w("          (Long.compareUnsigned(t" + (offset + j) + ", n" + j + ") < 0 || (t"
            + (offset + j) + " == n" + j + " && borrow != 0)) ? 1L : 0L;");
      }
    }
    w("    } else {");
    for (int j = 0; j < k; j++) {
      w("      out[" + j + "] = t" + (offset + j) + ";");
    }
    w("    }");
  }

  /**
   * The unrolled Montgomery squaring (separated operand scanning): every cross product
   * <code>a_i*a_j</code> once, doubled, plus the squares, followed by <code>k</code> reduction
   * steps.
   */
  private void sqr(int k) {
    final int size = 2 * k;
    w("");
    w("  /** {@link #sqr(long[], long[])} unrolled for " + k + " limbs. */");
    w("  private void sqr" + k + "(long[] a, long[] out) {");
    for (int j = 0; j < k; j++) {
      w("    final long a" + j + " = a[" + j + "];");
    }
    modulusLimbs(k);
    w("    long l;");
    w("    long h;");
    w("    long s;");
    w("    long s2;");
    w("    long c;");
    w("    long m;");
    for (int j = 0; j < size; j++) {
      w("    long t" + j + " = 0;");
    }
    w("");
    w("    // the products a_i*a_j with i < j");
    boolean[] written = new boolean[size];
    for (int i = 0; i < k - 1; i++) {
      boolean first = true;
      for (int j = i + 1; j < k; j++) {
        int p = i + j;
        w("    l = a" + i + " * a" + j + ";");
        w("    h = multiplyHighUnsigned(a" + i + ", a" + j + ");");
        if (written[p]) {
          w("    s = t" + p + " + l;");
          w("    h += carry(t" + p + ", l, s);");
          if (first) {
            w("    t" + p + " = s;");
          } else {
            w("    s2 = s + c;");
            w("    h += carry(s, c, s2);");
            w("    t" + p + " = s2;");
          }
        } else if (first) {
          w("    t" + p + " = l;");
        } else {
          w("    s = l + c;");
          w("    h += carry(l, c, s);");
          w("    t" + p + " = s;");
        }
        written[p] = true;
        w("    c = h;");
        first = false;
      }
      w("    t" + (i + k) + " = c;");
      written[i + k] = true;
    }
    w("    // double them");
    for (int j = size - 1; j > 0; j--) {
      w("    t" + j + " = (t" + j + " << 1) | (t" + (j - 1) + " >>> 63);");
    }
    w("    t0 <<= 1;");
    w("    // add the squares a_i^2");
    for (int i = 0; i < k; i++) {
      w("    l = a" + i + " * a" + i + ";");
      w("    h = multiplyHighUnsigned(a" + i + ", a" + i + ");");
      if (i == 0) {
        w("    s = t0 + l;");
        w("    c = carry(t0, l, s);");
        w("    t0 = s;");
      } else {
        w("    s = t" + (2 * i) + " + l;");
        w("    s2 = s + c;");
        w("    c = carry(t" + (2 * i) + ", l, s) + carry(s, c, s2);");
        w("    t" + (2 * i) + " = s2;");
      }
      w("    s = t" + (2 * i + 1) + " + h;");
      w("    s2 = s + c;");
      w("    c = carry(t" + (2 * i + 1) + ", h, s) + carry(s, c, s2);");
      w("    t" + (2 * i + 1) + " = s2;");
    }
    w("");
    w("    // Montgomery reduction; top is the carry into the next limb above i+k");
    w("    long top = 0;");
    for (int i = 0; i < k; i++) {
      w("    m = t" + i + " * nInverse;");
      for (int j = 0; j < k; j++) {
        int p = i + j;
        w("    l = m * n" + j + ";");
        w("    h = multiplyHighUnsigned(m, n" + j + ");");
        w("    s = t" + p + " + l;");
        w("    h += carry(t" + p + ", l, s);");
        if (j > 0) {
          w("    s2 = s + c;");
          w("    h += carry(s, c, s2);");
          w("    t" + p + " = s2;");
        }
        w("    c = h;");
      }
      int p = i + k;
      w("    s = t" + p + " + c;");
      w("    s2 = s + top;");
      w("    top = carry(t" + p + ", c, s) + carry(s, top, s2);");
      w("    t" + p + " = s2;");
    }
    w("");
    finalSubtraction(k, k, "top");
    w("  }");
  }

  /** The unrolled modular addition, which selects its result with a mask. */
  private void add(int k) {
    w("");
    w("  /** {@link #add(long[], long[], long[])} unrolled and without branches for " + k
        + " limbs. */");
    w("  private void add" + k + "(long[] a, long[] b, long[] out) {");
    operands(k);
    w("    // s = a + b with the carry c out of the top limb");
    w("    final long s0 = a0 + b0;");
    w("    long c = carry(a0, b0, s0);");
    for (int j = 1; j < k; j++) {
      w("    final long u" + j + " = a" + j + " + b" + j + ";");
      w("    final long s" + j + " = u" + j + " + c;");
      w("    c = carry(a" + j + ", b" + j + ", u" + j + ") | carry(u" + j + ", c, s" + j + ");");
    }
    w("    // d = s - n with the borrow r out of the top limb");
    w("    final long d0 = s0 - n0;");
    w("    long r = borrow(s0, n0, d0);");
    for (int j = 1; j < k; j++) {
      w("    final long e" + j + " = s" + j + " - n" + j + ";");
      w("    final long d" + j + " = e" + j + " - r;");
      w("    r = borrow(s" + j + ", n" + j + ", e" + j + ") | borrow(e" + j + ", r, d" + j + ");");
    }
    w("    // s >= n if s overflowed or d didn't borrow");
    w("    final long mask = -(c | (r ^ 1));");
    for (int j = 0; j < k; j++) {
      w("    out[" + j + "] = (d" + j + " & mask) | (s" + j + " & ~mask);");
    }
    w("  }");
  }

  /** The unrolled modular subtraction, which adds n back with a mask. */
  private void sub(int k) {
    w("");
    w("  /** {@link #sub(long[], long[], long[])} unrolled and without branches for " + k
        + " limbs. */");
    w("  private void sub" + k + "(long[] a, long[] b, long[] out) {");
    operands(k);
    w("    // d = a - b with the borrow r out of the top limb");
    w("    final long d0 = a0 - b0;");
    w("    long r = borrow(a0, b0, d0);");
    for (int j = 1; j < k; j++) {
      w("    final long e" + j + " = a" + j + " - b" + j + ";");
      w("    final long d" + j + " = e" + j + " - r;");
      w("    r = borrow(a" + j + ", b" + j + ", e" + j + ") | borrow(e" + j + ", r, d" + j + ");");
    }
    w("    // add n back if a < b");
    w("    final long mask = -r;");
    w("    final long m0 = n0 & mask;");
    w("    final long s0 = d0 + m0;");
    w("    long c = carry(d0, m0, s0);");
    for (int j = 1; j < k; j++) {
      w("    final long m" + j + " = n" + j + " & mask;");
      w("    final long u" + j + " = d" + j + " + m" + j + ";");
      w("    final long s" + j + " = u" + j + " + c;");
      if (j < k - 1) {
        w("    c = carry(d" + j + ", m" + j + ", u" + j + ") | carry(u" + j + ", c, s" + j
            + ");");
      }
    }
    for (int j = 0; j < k; j++) {
      w("    out[" + j + "] = s" + j + ";");
    }
    w("  }");
  }

  private void modulusLimbs(int k) {
    for (int j = 0; j < k; j++) {
      w("    final long n" + j + " = this.n" + j + ";");
    }
  }

  private void operands(int k) {
    for (int j = 0; j < k; j++) {
      w("    final long a" + j + " = a[" + j + "];");
    }
    for (int j = 0; j < k; j++) {
      w("    final long b" + j + " = b[" + j + "];");
    }
  }

  /** The generated region including the markers. */
  String generate() {
    out.setLength(0);
    w(BEGIN);
    // the unrolled methods repeat one pattern per limb count; keep the duplicate code check quiet
    w("  // CPD-OFF unrolled limb arithmetic, one copy per limb count");
    for (int k = 2; k <= 4; k++) {
      mul(k);
    }
    for (int k = 2; k <= 4; k++) {
      sqr(k);
    }
    for (int k = 2; k <= 4; k++) {
      add(k);
    }
    for (int k = 2; k <= 4; k++) {
      sub(k);
    }
    w("  // CPD-ON");
    w(END);
    return out.toString();
  }

  public static void main(String[] args) throws IOException {
    Path path = Paths.get(args.length > 0 ? args[0] : DEFAULT_PATH);
    String source = new String(Files.readAllBytes(path), StandardCharsets.UTF_8);
    int begin = source.indexOf(BEGIN);
    int end = source.indexOf(END);
    if (begin < 0 || end < begin) {
      throw new IllegalStateException("no generated region in " + path);
    }
    int endOfLine = source.indexOf('\n', end) + 1;
    String result =
        source.substring(0, begin) + new MontgomeryLimbsGenerator().generate()
            + source.substring(endOfLine);
    Files.write(path, result.getBytes(StandardCharsets.UTF_8));
    System.out.println("regenerated " + path);
  }
}
