package org.matheclipse.io.servlet;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;
import java.util.stream.Stream;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

/**
 * One directory per browser session, and the only part of the file system that session can reach.
 *
 * <p>
 * The servlets used to set {@link org.matheclipse.core.basic.Config#FILESYSTEM_ENABLED} to
 * <code>true</code>, which made <code>Import("/etc/passwd")</code> from a browser read the
 * <i>server's</i> disk by absolute path, and - once <code>Export</code> learned to write CSV and
 * XLSX - would have let it write anywhere the process can. Fine for a notebook you run on your own
 * machine; not fine for a process answering HTTP.
 * 
 * <p>
 * So the permission moves from the global switch onto the session's engine, and with it a root
 * directory that {@link org.matheclipse.core.io.FileSandbox} resolves every user supplied name
 * inside. The directory is created on first use and deleted when the session ends, next to the four
 * other per-session things {@link SymjaSessionListener} already releases.
 */
final class SessionSandbox {

  private static final Logger LOGGER = LogManager.getLogger(SessionSandbox.class);

  /**
   * Everything lives under one parent, so that a crash leaves a single directory to recognize and
   * sweep rather than session directories scattered through the temp directory.
   */
  private static final String PARENT_NAME = "symja-sessions";

  private SessionSandbox() {}

  /**
   * The directory of <code>sessionID</code>, created if it does not exist yet.
   *
   * @return the directory, or <code>null</code> if it cannot be created - in which case the session
   *         gets no file system access at all, which is the safe direction to fail in
   */
  static Path rootFor(String sessionID) {
    try {
      Path parent = Path.of(System.getProperty("java.io.tmpdir"), PARENT_NAME);
      // the session id is generated by the servlet container, but it ends up in a path, so only
      // characters that cannot climb out of the parent are kept
      Path root = parent.resolve(sessionID.replaceAll("[^A-Za-z0-9_-]", "_"));
      Files.createDirectories(root);
      return root.toRealPath();
    } catch (IOException | RuntimeException ex) {
      LOGGER.error("Could not create the sandbox directory of session {}", sessionID, ex);
      return null;
    }
  }

  /** The most one session's directory may hold, so that one browser cannot fill the disk. */
  static final long MAX_TOTAL_BYTES = 32L * 1024 * 1024;

  /** The most one uploaded or generated file may be. */
  static final long MAX_FILE_BYTES = 16L * 1024 * 1024;

  /** The most files one session's directory may hold. */
  static final int MAX_FILES = 64;

  /**
   * A file name safe to put in a path. The servlet container decides what a browser may call an
   * upload, so the name is reduced to characters that cannot climb out of the directory or mean
   * something to a shell.
   *
   * @return the sanitized name, or <code>null</code> if nothing usable is left
   */
  static String safeName(String name, String fallbackExtension) {
    if (name == null) {
      return null;
    }
    // a browser may send a full client side path
    int slash = Math.max(name.lastIndexOf('/'), name.lastIndexOf('\\'));
    String base = slash >= 0 ? name.substring(slash + 1) : name;
    base = base.replaceAll("[^A-Za-z0-9._-]", "_");
    while (base.startsWith(".")) {
      base = base.substring(1);
    }
    if (base.isEmpty()) {
      return fallbackExtension == null ? null : "file." + fallbackExtension;
    }
    return base.length() > 128 ? base.substring(base.length() - 128) : base;
  }

  /**
   * Write <code>bytes</code> into the session's directory under <code>name</code>, refusing to
   * exceed {@link #MAX_FILES} or {@link #MAX_TOTAL_BYTES}.
   *
   * @return the file, or <code>null</code> if it could not be written
   */
  static Path store(String sessionID, String name, byte[] bytes) {
    Path root = rootFor(sessionID);
    if (root == null || bytes == null || bytes.length > MAX_FILE_BYTES) {
      return null;
    }
    try (Stream<Path> children = Files.list(root)) {
      long total = 0;
      int count = 0;
      for (Path child : (Iterable<Path>) children::iterator) {
        count++;
        total += Files.size(child);
      }
      if (count >= MAX_FILES || total + bytes.length > MAX_TOTAL_BYTES) {
        LOGGER.warn("Session {} is at its sandbox quota", sessionID);
        return null;
      }
    } catch (IOException | RuntimeException ex) {
      LOGGER.error("Could not measure the sandbox directory of session {}", sessionID, ex);
      return null;
    }
    try {
      Path file = root.resolve(name).normalize();
      if (!file.startsWith(root)) {
        return null;
      }
      Files.write(file, bytes);
      return file;
    } catch (IOException | RuntimeException ex) {
      LOGGER.error("Could not write {} in the sandbox of session {}", name, sessionID, ex);
      return null;
    }
  }

  /**
   * An existing file in the session's directory.
   *
   * @return the file, or <code>null</code> if the name escapes the directory or does not exist
   */
  static Path read(String sessionID, String name) {
    Path root = rootFor(sessionID);
    if (root == null || name == null) {
      return null;
    }
    try {
      Path file = root.resolve(name).normalize();
      if (!file.startsWith(root) || !Files.isRegularFile(file)) {
        return null;
      }
      return file;
    } catch (RuntimeException ex) {
      return null;
    }
  }

  /** Delete the directory of a session that has ended, with everything in it. */
  static void remove(String sessionID) {
    Path root = Path.of(System.getProperty("java.io.tmpdir"), PARENT_NAME)
        .resolve(sessionID.replaceAll("[^A-Za-z0-9_-]", "_"));
    deleteRecursively(root);
  }

  /**
   * Delete the directories of sessions that ended when the server did. Called once at startup:
   * {@link SymjaSessionListener} never runs for a session the process died in the middle of.
   */
  static void sweepOrphans() {
    Path parent = Path.of(System.getProperty("java.io.tmpdir"), PARENT_NAME);
    if (!Files.isDirectory(parent)) {
      return;
    }
    try (Stream<Path> children = Files.list(parent)) {
      children.forEach(SessionSandbox::deleteRecursively);
    } catch (IOException | UncheckedIOException ex) {
      LOGGER.warn("Could not sweep {}", parent, ex);
    }
  }

  private static void deleteRecursively(Path root) {
    if (!Files.exists(root)) {
      return;
    }
    try {
      Files.walkFileTree(root, new SimpleFileVisitor<Path>() {
        @Override
        public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) throws IOException {
          Files.delete(file);
          return FileVisitResult.CONTINUE;
        }

        @Override
        public FileVisitResult postVisitDirectory(Path dir, IOException exc) throws IOException {
          Files.delete(dir);
          return FileVisitResult.CONTINUE;
        }
      });
    } catch (IOException | RuntimeException ex) {
      LOGGER.warn("Could not delete the sandbox directory {}", root, ex);
    }
  }
}
