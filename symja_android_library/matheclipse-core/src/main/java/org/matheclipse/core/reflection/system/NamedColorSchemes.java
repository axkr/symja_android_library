  private static Map<String, IAST> html() {
    Map<String, IAST> colors = new LinkedHashMap<>();
    for (String entry : HTML) {
      String[] parts = entry.split(",");
      // a zero channel stays exact
      colors.put(parts[0], F.RGBColor(channel(parts[1], parts[1].equals("0")),
          channel(parts[2], parts[2].equals("0")), channel(parts[3], parts[3].equals("0"))));
    }
    return colors;
  }

  private static Map<String, IAST> legacy() {
    Map<String, IAST> colors = new LinkedHashMap<>();
    for (String entry : LEGACY) {
      String[] parts = entry.split(",");
      int exact = Integer.parseInt(parts[4]);
      colors.put(parts[0], F.RGBColor(channel(parts[1], (exact & 1) != 0),
          channel(parts[2], (exact & 2) != 0), channel(parts[3], (exact & 4) != 0)));
    }
    return colors;
  }

  /** The colors of <code>name, r, g, b</code> entries, all of whose channels are machine reals. */
  private static Map<String, IAST> inexact(String[] entries) {
    Map<String, IAST> colors = new LinkedHashMap<>();
    for (String entry : entries) {
      String[] parts = entry.split(",");
      colors.put(parts[0], F.RGBColor(channel(parts[1], false), channel(parts[2], false),
          channel(parts[3], false)));
    }
    return colors;
  }

