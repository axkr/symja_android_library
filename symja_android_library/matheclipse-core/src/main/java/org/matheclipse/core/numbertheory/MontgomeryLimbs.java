  /** {@link #mul(long[], long[], long[])} for any number of limbs. */
  void mulGeneric(long[] a, long[] b, long[] out) {
    final int k = this.k;
    final long[] t = this.t;
    final long[] n = this.n;
    for (int j = 0; j < k + 2; j++) {
      t[j] = 0;
    }
    for (int i = 0; i < k; i++) {
      // t = t + a * b[i]
      final long bi = b[i];
      long c = 0;
      for (int j = 0; j < k; j++) {
        long l = a[j] * bi;
        long h = multiplyHighUnsigned(a[j], bi);
        long s = t[j] + l;
        h += carry(t[j], l, s);
        long s2 = s + c;
        h += carry(s, c, s2);
        t[j] = s2;
        c = h;
      }
      long s = t[k] + c;
      t[k + 1] = carry(t[k], c, s);
      t[k] = s;
      // t = (t + m * n) / 2^64
      final long m = t[0] * nInverse;
      long l = m * n[0];
      long h = multiplyHighUnsigned(m, n[0]);
      s = t[0] + l;
      c = h + carry(t[0], l, s);
      for (int j = 1; j < k; j++) {
        l = m * n[j];
        h = multiplyHighUnsigned(m, n[j]);
        s = t[j] + l;
        h += carry(t[j], l, s);
        long s2 = s + c;
        h += carry(s, c, s2);
        t[j - 1] = s2;
        c = h;
      }
      s = t[k] + c;
      t[k - 1] = s;
      t[k] = t[k + 1] + carry(t[k], c, s);
    }
    reduceOnce(t, t[k], out);
  }

  /** {@link #add(long[], long[], long[])} for any number of limbs, without branches. */
  void addGeneric(long[] a, long[] b, long[] out) {
    final long[] s = t;
    long c = 0;
    for (int j = 0; j < k; j++) {
      final long u = a[j] + b[j];
      final long sj = u + c;
      c = carry(a[j], b[j], u) | carry(u, c, sj);
      s[j] = sj;
    }
    // d = s - n into out; select s or d with a mask
    long r = 0;
    for (int j = 0; j < k; j++) {
      final long e = s[j] - n[j];
      final long d = e - r;
      r = borrow(s[j], n[j], e) | borrow(e, r, d);
      out[j] = d;
    }
    final long mask = -(c | (r ^ 1));
    for (int j = 0; j < k; j++) {
      out[j] = (out[j] & mask) | (s[j] & ~mask);
    }
  }

  /** {@link #sub(long[], long[], long[])} for any number of limbs, without branches. */
  void subGeneric(long[] a, long[] b, long[] out) {
    long r = 0;
    for (int j = 0; j < k; j++) {
      final long e = a[j] - b[j];
      final long d = e - r;
      r = borrow(a[j], b[j], e) | borrow(e, r, d);
      out[j] = d;
    }
    final long mask = -r;
    long c = 0;
    for (int j = 0; j < k; j++) {
      final long m = n[j] & mask;
      final long u = out[j] + m;
      final long s = u + c;
      c = carry(out[j], m, u) | carry(u, c, s);
      out[j] = s;
    }
  }

  /**
   * <code>out = x mod n</code> for the number <code>x = high*2^(64*k) + x[0..k-1] &lt; 2n</code>.
   */
  private void reduceOnce(long[] x, long high, long[] out) {
    boolean subtract = high != 0;
    if (!subtract) {
      subtract = true;
      for (int j = k - 1; j >= 0; j--) {
        if (x[j] != n[j]) {
          subtract = Long.compareUnsigned(x[j], n[j]) > 0;
          break;
        }
      }
    }
    if (subtract) {
      long borrow = 0;
      for (int j = 0; j < k; j++) {
        long xj = x[j];
        long nj = n[j];
        out[j] = xj - nj - borrow;
        borrow = (Long.compareUnsigned(xj, nj) < 0 || (xj == nj && borrow != 0)) ? 1L : 0L;
      }
    } else if (x != out) {
      System.arraycopy(x, 0, out, 0, k);
    }
  }

  /** <code>out</code> = the Montgomery form of <code>0 &lt;= x &lt; n</code>. */
  void toMontgomery(BigInteger x, long[] out) {
    mul(toLimbs(x, k), r2, out);
  }

  /**
   * <code>out</code> = the Montgomery form of <code>x^(-1)</code> for the Montgomery form
   * <code>a</code> of <code>x</code>, which must be invertible modulo <code>n</code>.
   */
  void inverse(long[] a, long[] out) {
    // (x*R)^(-1) * R^2 = x^(-1) * R
    toMontgomery(toBigInteger(a).modInverse(modulus), out);
    mul(out, r2, out);
  }

  /** The gcd of the residue with Montgomery form <code>a</code> and the modulus. */
  BigInteger gcd(long[] a) {
    return toBigInteger(a).gcd(modulus);
  }

  /** The <code>k</code> lowest limbs of <code>x &gt;= 0</code>. */
  static long[] toLimbs(BigInteger x, int k) {
    long[] limbs = new long[k];
    for (int j = 0; j < k; j++) {
      limbs[j] = x.shiftRight(64 * j).longValue();
    }
    return limbs;
  }

  /** The unsigned number with the limbs <code>a</code>, least significant first. */
  static BigInteger toBigInteger(long[] a) {
    byte[] bytes = new byte[8 * a.length + 1];
    for (int j = 0; j < a.length; j++) {
      long limb = a[j];
      for (int i = 0; i < 8; i++) {
        bytes[bytes.length - 1 - 8 * j - i] = (byte) (limb >>> (8 * i));
      }
    }
    return new BigInteger(bytes);
  }

