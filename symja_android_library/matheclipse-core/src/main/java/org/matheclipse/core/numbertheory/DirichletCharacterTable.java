package org.matheclipse.core.numbertheory;

import java.math.BigInteger;
import java.util.HashMap;
import java.util.Map;
import java.util.SortedMap;
import java.util.concurrent.ConcurrentHashMap;
import org.matheclipse.core.expression.F;
import org.matheclipse.core.expression.S;
import org.matheclipse.core.interfaces.IExpr;

/**
 * The Dirichlet character <code>chi</code> modulo <code>k</code> with index <code>j</code>, in the
 * labelling of <code>DirichletCharacter(k, j, n)</code>.
 *
 * <p>
 * <b>Labelling.</b> Factor <code>k</code> with the primes ascending. The unit group
 * <code>(Z/kZ)^*</code> splits into cyclic components:
 * <ul>
 * <li>an odd prime power <code>p^a</code>: one component, generated by the smallest primitive
 * root modulo <code>p^a</code>, of order <code>EulerPhi(p^a)</code>;</li>
 * <li><code>4</code>: one component, generated by <code>3 = -1</code>, of order 2;</li>
 * <li><code>2^a, a &gt;= 3</code>: the sign component <code>&lt;-1&gt;</code> of order 2, then the
 * component <code>&lt;5&gt;</code> of order <code>2^(a-2)</code>;</li>
 * <li><code>2</code>: none.</li>
 * </ul>
 * <code>j-1</code> is written in mixed radix over the components, the first component most
 * significant: <code>j-1 = sum_c d_c * prod_(c' after c) ord_c'</code>, and
 * <code>chi(g_c) = Exp(2*Pi*I*d_c/ord_c)</code> on the generator of each component. So
 * <code>j = 1</code> is the principal character, and for a prime <code>k</code> with smallest
 * primitive root <code>g</code>, <code>chi(g) = Exp(2*Pi*I*(j-1)/(k-1))</code>.
 *
 * <p>
 * Every value is a root of unity <code>Exp(2*Pi*I*e/order)</code>; the methods work with the
 * exponent <code>e</code> modulo the order of the character, exactly. Single values use discrete
 * logarithms (Pohlig-Hellman, baby-step giant-step in the prime-order subgroups); the table of the
 * primitive character over a period is built by walking the powers of the generators.
 *
 * <p>
 * The table also holds the conductor <code>f</code> of the character, the induced primitive
 * character <code>chi*</code> modulo <code>f</code>, and the primes which divide <code>k</code>
 * but not <code>f</code>: <code>L(s, chi) = L(s, chi*) * prod (1 - chi*(p)*p^(-s))</code>.
 *
 * <p>
 * Instances are immutable once built.
 */
public final class DirichletCharacterTable {

  /** Largest conductor for which {@link #starExponents()} builds a table. */
  public static final long TABLE_MAX = 1L << 22;

  /** Largest conductor whose tables are cached. */
  private static final long CACHE_FMAX = 1L << 16;

  private static final int CACHE_SLOTS = 256;

  private static final Map<Long, DirichletCharacterTable> CACHE = new ConcurrentHashMap<>();

  private static final int CYCLIC = 0;

  private static final int SIGN = 1;

  private static final int FIVE = 2;

  /** One cyclic component of <code>(Z/p^a)^*</code>. */
  private static final class Component {
    int kind;
    /** generator modulo the prime power */
    long g;
    long ord;
    /** this character's digit, <code>0 &lt;= d &lt; ord</code> */
    long d;
    /** the prime factorization of <code>ord</code>, for Pohlig-Hellman */
    long[] facP = new long[0];
    int[] facE = new int[0];

    /** <code>d/ord</code> in lowest terms as <code>{numerator, denominator}</code>. */
    long[] reduced() {
      if (d == 0) {
        return new long[] {0, 1};
      }
      long gcd = gcd(d, ord);
      return new long[] {d / gcd, ord / gcd};
    }
  }

  /** The part of <code>k</code> at one prime. */
  private static final class Part {
    long p;
    int a;
    /** <code>p^a</code> */
    long q;
    /** conductor exponent: the character's <code>p</code>-part has conductor <code>p^b</code> */
    int b;
    /** <code>p^b</code> */
    long qb;
    Component[] comp;
  }

  private final long k;

  private final long j;

  private Part[] parts;

  private long order;

  private int odd;

  private long conductor;

  private long[] eulerPrimes;

  private long[] eulerExponents;

  /** exponents of <code>chi*(a)</code> over <code>a = 0..f-1</code>, <code>-1</code> if not coprime */
  private volatile int[] starExponents;

  private DirichletCharacterTable(long k, long j) {
    this.k = k;
    this.j = j;
  }

  // ----------------------------------------------------------------------------------------
  // modular arithmetic for moduli below 2^63
  // ----------------------------------------------------------------------------------------

  public static long gcd(long a, long b) {
    while (b != 0) {
      long r = a % b;
      a = b;
      b = r;
    }
    return a;
  }

  public static long mulMod(long a, long b, long m) {
    a %= m;
    b %= m;
    if (a < 3037000499L && b < 3037000499L) {
      return (a * b) % m;
    }
    return BigInteger.valueOf(a).multiply(BigInteger.valueOf(b)).mod(BigInteger.valueOf(m))
        .longValue();
  }

  public static long powMod(long b, long e, long m) {
    if (m == 1) {
      return 0;
    }
    long r = 1;
    b %= m;
    while (e != 0) {
      if ((e & 1) != 0) {
        r = mulMod(r, b, m);
      }
      e >>= 1;
      if (e != 0) {
        b = mulMod(b, b, m);
      }
    }
    return r;
  }

  /** The inverse of <code>a</code> modulo <code>m</code>, for <code>gcd(a, m) = 1</code>. */
  private static long inverseMod(long a, long m) {
    long t = 0;
    long nt = 1;
    long r = m;
    long nr = a % m;
    while (nr != 0) {
      long q = r / nr;
      long tmp = t - q * nt;
      t = nt;
      nt = tmp;
      long rr = r - q * nr;
      r = nr;
      nr = rr;
    }
    if (t < 0) {
      t += m;
    }
    return t;
  }

  /** The prime factorization of <code>n &gt;= 1</code>, primes ascending. */
  private static SortedMap<BigInteger, Integer> factor(long n) {
    return new Primality().factorInteger(BigInteger.valueOf(n));
  }

  // ----------------------------------------------------------------------------------------
  // discrete logarithms
  // ----------------------------------------------------------------------------------------

  /**
   * The logarithm to base <code>gamma</code> of <code>h</code> in the subgroup of prime order
   * <code>l</code> modulo <code>q</code>, or <code>-1</code>.
   */
  private static long logPrime(long h, long gamma, long l, long q) {
    if (h == 1) {
      return 0;
    }
    if (l <= 4096) {
      long current = 1;
      for (long i = 0; i < l; i++) {
        if (current == h) {
          return i;
        }
        current = mulMod(current, gamma, q);
      }
      return -1;
    }
    if (l > (1L << 44)) {
      return -1; // more than 2^22 baby steps
    }
    final long m = (long) Math.ceil(Math.sqrt((double) l));
    Map<Long, Long> baby = new HashMap<>((int) Math.min(m * 2, Integer.MAX_VALUE / 2));
    long current = 1;
    for (long i = 0; i < m; i++) {
      baby.putIfAbsent(current, i);
      current = mulMod(current, gamma, q);
    }
    final long step = powMod(gamma, l - (m % l), q); // gamma^(-m)
    long y = h;
    for (long giant = 0; giant <= m; giant++) {
      Long hit = baby.get(y);
      if (hit != null) {
        return (giant * m + hit) % l;
      }
      y = mulMod(y, step, q);
    }
    return -1;
  }

  /**
   * The logarithm to base <code>g</code> of <code>x</code> modulo <code>q</code>, where
   * <code>g</code> generates the cyclic group of component <code>c</code>, or <code>-1</code>.
   */
  private static long logComponent(long x, long g, long q, Component c) {
    final long n = c.ord;
    if (n == 1) {
      return 0;
    }
    long t = 0;
    for (int i = 0; i < c.facP.length; i++) {
      final long l = c.facP[i];
      final int e = c.facE[i];
      long pe = 1;
      for (int s = 0; s < e; s++) {
        pe *= l;
      }
      final long gg = powMod(g, n / pe, q); // of order pe
      final long hh = powMod(x, n / pe, q);
      final long gamma = powMod(gg, pe / l, q); // of order l
      long y = 0;
      long lk = 1;
      for (int s = 0; s < e; s++) {
        // (hh * gg^-y)^(pe / l^(s+1))
        final long ginv = powMod(gg, (pe - (y % pe)) % pe, q);
        long z = mulMod(hh, ginv, q);
        z = powMod(z, pe / (lk * l), q);
        final long digit = logPrime(z, gamma, l, q);
        if (digit < 0) {
          return -1;
        }
        y += digit * lk;
        lk *= l;
      }
      // CRT of t modulo n/pe and y modulo pe
      final long cofactor = n / pe;
      final long coef = mulMod(cofactor, inverseMod(cofactor % pe, pe), n);
      t = (t + mulMod(y % pe, coef, n)) % n;
    }
    return t;
  }

  /** The logarithm of the unit <code>x</code> modulo <code>part.q</code> in component <code>c</code>. */
  private static long logOf(Part part, Component c, long x) {
    switch (c.kind) {
      case SIGN:
        return (x % 4 == 3) ? 1 : 0;
      case FIVE: {
        long m = x % part.q;
        if (m % 4 == 3) {
          m = part.q - m;
        }
        return logComponent(m, 5, part.q, c);
      }
      default:
        return logComponent(x % part.q, c.g, part.q, c);
    }
  }

  /** The contribution of component <code>c</code> at logarithm <code>t</code>, over the order. */
  private static long contribution(Component c, long t, long order) {
    long[] r = c.reduced();
    if (r[1] == 1) {
      return 0;
    }
    long v = mulMod(r[0], t % r[1], r[1]);
    return mulMod(v, order / r[1], order);
  }

  // ----------------------------------------------------------------------------------------
  // construction
  // ----------------------------------------------------------------------------------------

  /**
   * Set the prime factorization of <code>ord = p^(a-1)*(p-1)</code> of an odd prime power's
   * component, ascending.
   */
  private static void setCyclicFactors(Component c, long p, int a) {
    SortedMap<BigInteger, Integer> pm1 = factor(p - 1);
    Map<Long, Integer> merged = new java.util.TreeMap<>();
    for (Map.Entry<BigInteger, Integer> e : pm1.entrySet()) {
      merged.put(e.getKey().longValue(), e.getValue());
    }
    if (a > 1) {
      merged.merge(p, a - 1, Integer::sum);
    }
    c.facP = new long[merged.size()];
    c.facE = new int[merged.size()];
    int i = 0;
    for (Map.Entry<Long, Integer> e : merged.entrySet()) {
      c.facP[i] = e.getKey();
      c.facE[i] = e.getValue();
      i++;
    }
  }

  /** The smallest primitive root modulo <code>q = p^a</code>, <code>p</code> odd. */
  private static long smallestPrimitiveRoot(long p, long q, Component c) {
    for (long g = 2; g < q; g++) {
      if (g % p == 0) {
        continue;
      }
      boolean ok = true;
      for (int i = 0; i < c.facP.length && ok; i++) {
        if (powMod(g, c.ord / c.facP[i], q) == 1) {
          ok = false;
        }
      }
      if (ok) {
        return g;
      }
    }
    return 0;
  }

  /**
   * <code>EulerPhi(k)</code>, the number of characters modulo <code>k</code>.
   *
   * @param k a modulus <code>&gt;= 1</code>
   */
  public static long eulerPhi(long k) {
    long phi = 1;
    for (Map.Entry<BigInteger, Integer> e : factor(k).entrySet()) {
      long p = e.getKey().longValue();
      phi *= p - 1;
      for (int i = 1; i < e.getValue(); i++) {
        phi *= p;
      }
    }
    return phi;
  }

  /**
   * The character with index <code>j</code> modulo <code>k</code>.
   *
   * @param k the modulus, <code>k &gt;= 1</code>
   * @param j the index, <code>1 &lt;= j &lt;= EulerPhi(k)</code>
   * @return <code>null</code> if <code>j</code> is out of range or a discrete logarithm is out of
   *         reach
   */
  public static DirichletCharacterTable of(long k, long j) {
    if (k < 1 || j < 1) {
      return null;
    }
    final Long key = k * 1000003L + j;
    DirichletCharacterTable cached = CACHE.get(key);
    if (cached != null && cached.k == k && cached.j == j) {
      return cached;
    }
    DirichletCharacterTable table = build(k, j);
    if (table != null && table.conductor <= CACHE_FMAX && CACHE.size() < CACHE_SLOTS) {
      CACHE.putIfAbsent(key, table);
    }
    return table;
  }

  private static DirichletCharacterTable build(long k, long j) {
    DirichletCharacterTable t = new DirichletCharacterTable(k, j);
    SortedMap<BigInteger, Integer> factors = factor(k);
    t.parts = new Part[factors.size()];
    long phi = 1;
    int index = 0;
    for (Map.Entry<BigInteger, Integer> e : factors.entrySet()) {
      Part part = new Part();
      part.p = e.getKey().longValue();
      part.a = e.getValue();
      part.q = 1;
      for (int s = 0; s < part.a; s++) {
        part.q *= part.p;
      }
      if (part.p == 2) {
        java.util.List<Component> list = new java.util.ArrayList<>(2);
        if (part.a >= 2) {
          Component sign = new Component();
          sign.kind = SIGN;
          sign.g = part.q - 1;
          sign.ord = 2;
          sign.facP = new long[] {2};
          sign.facE = new int[] {1};
          list.add(sign);
        }
        if (part.a >= 3) {
          Component five = new Component();
          five.kind = FIVE;
          five.g = 5;
          five.ord = part.q >> 2;
          five.facP = new long[] {2};
          five.facE = new int[] {part.a - 2};
          list.add(five);
        }
        part.comp = list.toArray(new Component[0]);
      } else {
        Component c = new Component();
        c.kind = CYCLIC;
        c.ord = part.q / part.p * (part.p - 1);
        setCyclicFactors(c, part.p, part.a);
        c.g = smallestPrimitiveRoot(part.p, part.q, c);
        if (c.g == 0) {
          return null;
        }
        part.comp = new Component[] {c};
      }
      for (Component c : part.comp) {
        phi *= c.ord;
      }
      t.parts[index++] = part;
    }
    if (j > phi) {
      return null;
    }

    // mixed radix digits, the last component least significant
    long r = j - 1;
    for (int i = t.parts.length - 1; i >= 0; i--) {
      Component[] comp = t.parts[i].comp;
      for (int c = comp.length - 1; c >= 0; c--) {
        comp[c].d = r % comp[c].ord;
        r /= comp[c].ord;
      }
    }

    // order, parity and conductor
    long order = 1;
    int odd = 0;
    long f = 1;
    for (Part part : t.parts) {
      for (Component c : part.comp) {
        long o = c.reduced()[1];
        order = order / gcd(order, o) * o;
        if (c.kind != FIVE) {
          odd ^= (int) (c.d & 1);
        }
      }
      part.b = 0;
      if (part.p != 2) {
        long o = part.comp[0].reduced()[1];
        if (o > 1) {
          int v = 0;
          while (o % part.p == 0) {
            o /= part.p;
            v++;
          }
          part.b = v + 1;
        }
      } else if (part.comp.length > 0) {
        long ds = part.comp[0].d;
        long o5 = part.comp.length > 1 ? part.comp[1].reduced()[1] : 1;
        if (o5 > 1) {
          int c2 = 0;
          while (o5 > 1) {
            o5 >>= 1;
            c2++;
          }
          part.b = c2 + 2;
        } else if (ds != 0) {
          part.b = 2;
        }
      }
      part.qb = 1;
      for (int s = 0; s < part.b; s++) {
        part.qb *= part.p;
      }
      f *= part.qb;
    }
    t.order = order;
    t.odd = odd;
    t.conductor = f;

    // the Euler factors of the primes dividing k but not f
    int count = 0;
    for (Part part : t.parts) {
      if (part.b == 0) {
        count++;
      }
    }
    t.eulerPrimes = new long[count];
    t.eulerExponents = new long[count];
    count = 0;
    for (Part part : t.parts) {
      if (part.b == 0) {
        long e = t.starExponent(part.p);
        if (e < 0) {
          return null;
        }
        t.eulerPrimes[count] = part.p;
        t.eulerExponents[count] = e;
        count++;
      }
    }
    return t;
  }

  // ----------------------------------------------------------------------------------------
  // values
  // ----------------------------------------------------------------------------------------

  /**
   * The exponent of <code>chi*(n)</code> over the {@link #order()}, for the primitive character.
   *
   * @return <code>-1</code> if <code>gcd(n, f) &gt; 1</code> or a logarithm is out of reach
   */
  public long starExponent(long n) {
    long acc = 0;
    for (Part part : parts) {
      if (part.b == 0) {
        continue;
      }
      if (n % part.p == 0) {
        return -1;
      }
      for (Component c : part.comp) {
        if (c.d == 0) {
          continue;
        }
        long t = logOf(part, c, n);
        if (t < 0) {
          return -1;
        }
        acc = (acc + contribution(c, t, order)) % order;
      }
    }
    return acc;
  }

  /**
   * The exponent of <code>chi(n)</code> over the {@link #order()}, for <code>n &gt;= 0</code>.
   *
   * @return <code>-1</code> if <code>gcd(n, k) &gt; 1</code>, where <code>chi(n) = 0</code>
   */
  public long exponent(long n) {
    if (k > 1 && gcd(n % k, k) != 1) {
      return -1;
    }
    if (order == 1) {
      return 0;
    }
    return starExponent(n);
  }

  /**
   * The exponents of <code>chi*(a)</code> for <code>a = 0..f-1</code>, <code>-1</code> where
   * <code>gcd(a, f) &gt; 1</code>; built by walking the powers of the component generators.
   *
   * @return <code>null</code> if the conductor is above {@link #TABLE_MAX}
   */
  public int[] starExponents() {
    int[] table = starExponents;
    if (table != null) {
      return table;
    }
    if (conductor > TABLE_MAX) {
      return null;
    }
    final int f = (int) conductor;
    table = new int[f];
    for (Part part : parts) {
      if (part.b == 0) {
        continue;
      }
      final int qb = (int) part.qb;
      int[] e = new int[qb];
      java.util.Arrays.fill(e, -1);
      if (part.p != 2) {
        Component c = part.comp[0];
        long phib = qb / part.p * (part.p - 1);
        long g = c.g % qb;
        long x = 1;
        for (long t = 0; t < phib; t++) {
          e[(int) x] = (int) contribution(c, t, order);
          x = mulMod(x, g, qb);
        }
      } else {
        Component sign = part.comp[0];
        Component five = part.comp.length > 1 ? part.comp[1] : null;
        long n5 = (part.b >= 3) ? (qb >> 2) : 1;
        for (int sg = 0; sg < 2; sg++) {
          long x = 1;
          for (long t = 0; t < n5; t++) {
            long y = sg != 0 ? (qb - x) % qb : x;
            long v = contribution(sign, sg, order);
            if (five != null) {
              v = (v + contribution(five, t, order)) % order;
            }
            e[(int) y] = (int) v;
            x = mulMod(x, 5, qb);
          }
        }
      }
      for (int a = 0; a < f; a++) {
        if (table[a] < 0) {
          continue;
        }
        int v = e[a % qb];
        table[a] = (v < 0) ? -1 : (int) ((table[a] + (long) v) % order);
      }
    }
    if (f > 1) {
      table[0] = -1;
    }
    starExponents = table;
    return table;
  }

  /**
   * <code>Exp(2*Pi*I*numerator/denominator)</code>: <code>1, -1, I, -I</code>, or
   * <code>E^(I*Pi*r)</code> with a rational <code>-1 &lt; r &lt; 1</code>, evaluated.
   */
  public static IExpr rootOfUnity(long numerator, long denominator) {
    if (denominator <= 0) {
      denominator = 1;
    }
    numerator = Math.floorMod(numerator, denominator);
    if (numerator == 0) {
      return F.C1;
    }
    long g = gcd(numerator, denominator);
    numerator /= g;
    denominator /= g;
    if ((4 * numerator) % denominator == 0) {
      switch ((int) (4 * numerator / denominator)) {
        case 1:
          return F.CI;
        case 2:
          return F.CN1;
        default:
          return F.CNI;
      }
    }
    // Exp(2*Pi*I*n/d) = E^(I*Pi*r), r = 2n/d folded into (-1, 1)
    long rn = 2 * numerator;
    if (rn > denominator) {
      rn -= 2 * denominator;
    }
    return F.Power(S.E, F.Times(F.CI, F.QQ(rn, denominator), S.Pi)).eval();
  }

  /** <code>chi(n)</code> for an integer <code>0 &lt;= n &lt; k</code>, or <code>null</code>. */
  public IExpr value(long n) {
    long e = exponent(n);
    if (e < 0) {
      if (k > 1 && gcd(n % k, k) != 1) {
        return F.C0;
      }
      return null; // a discrete logarithm out of reach
    }
    return rootOfUnity(e, order);
  }

  public long modulus() {
    return k;
  }

  public long index() {
    return j;
  }

  /** The order of the character: its values are the <code>order</code>-th roots of unity. */
  public long order() {
    return order;
  }

  public boolean isPrincipal() {
    return order == 1;
  }

  /** Whether all values are real: <code>0, 1, -1</code>. */
  public boolean isReal() {
    return order <= 2;
  }

  /** <code>chi(-1) = (-1)^parity()</code>. */
  public int parity() {
    return odd;
  }

  public long conductor() {
    return conductor;
  }

  /** The primes dividing <code>k</code> but not the conductor. */
  public long[] eulerPrimes() {
    return eulerPrimes;
  }

  /** The exponents of <code>chi*(p)</code> over the order, for the {@link #eulerPrimes()}. */
  public long[] eulerExponents() {
    return eulerExponents;
  }
}
