package org.matheclipse.core.reflection.system;

import java.math.BigInteger;
import org.matheclipse.core.convert.Convert;
import org.matheclipse.core.eval.Errors;
import org.matheclipse.core.eval.EvalEngine;
import org.matheclipse.core.eval.interfaces.AbstractFunctionEvaluator;
import org.matheclipse.core.expression.F;
import org.matheclipse.core.expression.S;
import org.matheclipse.core.interfaces.IAST;
import org.matheclipse.core.interfaces.IASTAppendable;
import org.matheclipse.core.interfaces.IExpr;
import org.matheclipse.core.interfaces.IInteger;
import org.matheclipse.core.interfaces.IRational;
import org.matheclipse.core.numbertheory.LLL;

/**
 * LatticeReduce(matrix)
 *
 * <p>
 * Gives a reduced basis for the lattice generated by the rows of <code>matrix</code>, using the
 * Lenstra-Lenstra-Lov&aacute;sz algorithm.
 */
public class LatticeReduce extends AbstractFunctionEvaluator {

  public LatticeReduce() {}

  @Override
  public IExpr evaluate(final IAST ast, final EvalEngine engine) {
    IExpr arg1 = ast.arg1();
    if (!arg1.isList()) {
      return F.NIL;
    }
    if (arg1.isEmptyList()) {
      return F.CEmptyList;
    }
    int[] dim = Convert.checkNonEmptyRectangularMatrix(S.LatticeReduce, arg1);
    if (dim == null) {
      return F.NIL;
    }

    try {
      BigInteger[][] rows = Convert.list2BigIntegerMatrix(arg1);
      if (rows != null) {
        return matrix2List(LLL.reduce(rows));
      }

      // rational entries: scale all rows by the least common multiple of the denominators, reduce
      // the resulting integer lattice and scale the result back. Being LLL reduced is invariant
      // under a common positive scaling factor.
      IRational[][] rationalRows = Convert.list2RationalMatrix(arg1);
      if (rationalRows == null) {
        return F.NIL;
      }
      IInteger lcm = F.C1;
      for (int i = 0; i < rationalRows.length; i++) {
        for (int j = 0; j < rationalRows[i].length; j++) {
          lcm = lcm.lcm(rationalRows[i][j].denominator());
        }
      }
      BigInteger[][] scaled = new BigInteger[rationalRows.length][];
      for (int i = 0; i < rationalRows.length; i++) {
        scaled[i] = new BigInteger[rationalRows[i].length];
        for (int j = 0; j < rationalRows[i].length; j++) {
          scaled[i][j] = ((IRational) rationalRows[i][j].multiply(lcm)).toBigNumerator();
        }
      }
      BigInteger[][] reduced = LLL.reduce(scaled);
      BigInteger denominator = lcm.toBigNumerator();
      IASTAppendable result = F.ListAlloc(reduced.length);
      for (BigInteger[] row : reduced) {
        IASTAppendable vector = F.ListAlloc(row.length);
        for (BigInteger value : row) {
          vector.append(F.fraction(value, denominator));
        }
        result.append(vector);
      }
      // because the rows are sub lists the IAST.IS_MATRIX flag cannot be set directly
      result.isMatrix(true);
      return result;
    } catch (RuntimeException rex) {
      return Errors.printMessage(S.LatticeReduce, rex);
    }
  }

  private static IExpr matrix2List(BigInteger[][] matrix) {
    IASTAppendable result = F.ListAlloc(matrix.length);
    for (BigInteger[] row : matrix) {
      IASTAppendable vector = F.ListAlloc(row.length);
      for (BigInteger value : row) {
        vector.append(F.ZZ(value));
      }
      result.append(vector);
    }
    // because the rows are sub lists the IAST.IS_MATRIX flag cannot be set directly
    result.isMatrix(true);
    return result;
  }

  @Override
  public int[] expectedArgSize(IAST ast) {
    return ARGS_1_1;
  }
}
