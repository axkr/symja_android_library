package org.matheclipse.dataset.geo;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.zip.GZIPInputStream;

/**
 * The country table <code>countries.tsv.gz</code>, read once on first use.
 *
 * <p>
 * One row per country, sorted by its entity name, with the columns entity name, name, full name,
 * ISO 3166-1 alpha-2, alpha-3 and numeric code (a code may be a missing value like
 * <code>Missing[NotApplicable]</code>), continent (empty if there is none), the further classes
 * it belongs to (<code>"Unlisted"</code> for a country known by name but not listed among all
 * countries), the entity names of its neighbours, four yearly series (population, GDP in US
 * dollars, surface area and land area in square kilometres) and its shape. A series is written
 * <code>firstYear:v1,v2,...</code> with an empty field for a missing year, or is a missing value
 * like <code>Missing[NoResidentPopulation]</code>. A shape is a list of
 * rings separated by <code>;</code>, each ring its first point followed by the differences to the
 * previous point, as <code>lon,lat</code> pairs in thousandths of a degree.
 *
 * <p>
 * The table is generated by <code>matheclipse-dataset/tools/build_geo_data.py</code>; see
 * <code>NOTICE-geodata.txt</code> next to it for the sources and their licence.
 */
final class CountryTable {

  /** The resource with the table, relative to this class. */
  static final String RESOURCE = "countries.tsv.gz";

  /** The series columns, in the order of the table. */
  static final String[] SERIES = {"Population", "GDP", "Area", "LandArea"};

  /** One country of the table. */
  static final class Country {
    final String entity;
    final String name;
    final String fullName;
    final String code;
    final String unCode;
    final String continent;
    final List<String> classes;
    final List<String> neighbours;
    /** The raw series, in the order of {@link #SERIES}. */
    private final String[] series;
    /** The parsed series, filled on first use. */
    private final Series[] parsed = new Series[SERIES.length];
    private final String shape;

    private Country(String[] columns) {
      entity = columns[0];
      name = columns[1];
      fullName = columns[2];
      code = columns[3];
      unCode = columns[4];
      continent = columns[6];
      classes = split(columns[7], ',');
      neighbours = split(columns[8], ',');
      series = new String[] {columns[9], columns[10], columns[11], columns[12]};
      shape = columns[13];
    }

    /** The series of a property of {@link #SERIES}, or <code>null</code> if it is none. */
    synchronized Series series(String property) {
      for (int i = 0; i < SERIES.length; i++) {
        if (SERIES[i].equals(property)) {
          if (parsed[i] == null) {
            parsed[i] = Series.parse(series[i]);
          }
          return parsed[i];
        }
      }
      return null;
    }

    /**
     * The outer rings of the country's shape as <code>{lon, lat}</code> pairs in degrees; empty if
     * no shape is known.
     */
    List<double[][]> rings() {
      List<double[][]> rings = new ArrayList<double[][]>();
      if (shape.isEmpty()) {
        return rings;
      }
      for (String ring : split(shape, ';')) {
        List<String> points = split(ring, ' ');
        double[][] coordinates = new double[points.size()][];
        long x = 0;
        long y = 0;
        for (int i = 0; i < coordinates.length; i++) {
          String point = points.get(i);
          int comma = point.indexOf(',');
          x += Long.parseLong(point.substring(0, comma));
          y += Long.parseLong(point.substring(comma + 1));
          coordinates[i] = new double[] {x / 1000.0, y / 1000.0};
        }
        rings.add(coordinates);
      }
      return rings;
    }
  }

  /**
   * A yearly series; <code>Double.NaN</code> marks a missing year. A series without values may
   * carry the reason why there are none.
   */
  static final class Series {
    final int firstYear;
    final double[] values;
    /** The reason of a missing series like <code>NoResidentPopulation</code>, or null. */
    final String missingReason;

    private Series(int firstYear, double[] values, String missingReason) {
      this.firstYear = firstYear;
      this.values = values;
      this.missingReason = missingReason;
    }

    /** Whether a property is one of the yearly series of {@link CountryTable#SERIES}. */
    static boolean isSeries(String property) {
      for (String series : SERIES) {
        if (series.equals(property)) {
          return true;
        }
      }
      return false;
    }

    static Series parse(String text) {
      if (text.isEmpty()) {
        return new Series(0, new double[0], null);
      }
      if (isMissing(text)) {
        return new Series(0, new double[0], text.substring("Missing[".length(), text.length() - 1));
      }
      int colon = text.indexOf(':');
      int firstYear = Integer.parseInt(text.substring(0, colon));
      List<String> fields = split(text.substring(colon + 1), ',', true);
      double[] values = new double[fields.size()];
      for (int i = 0; i < values.length; i++) {
        String field = fields.get(i);
        values[i] = field.isEmpty() ? Double.NaN : Double.parseDouble(field);
      }
      return new Series(firstYear, values, null);
    }

    /** The value of a year, <code>NaN</code> if it is not known. */
    double value(int year) {
      int i = year - firstYear;
      return i >= 0 && i < values.length ? values[i] : Double.NaN;
    }

    /** The latest year with a value, or -1 if there is none. */
    int latestYear() {
      for (int i = values.length - 1; i >= 0; i--) {
        if (!Double.isNaN(values[i])) {
          return firstYear + i;
        }
      }
      return -1;
    }
  }

  private static final class Holder {
    static final CountryTable TABLE = load();
  }

  /**
   * The class of the countries which are known by name but are not listed among all countries.
   */
  static final String UNLISTED = "Unlisted";

  /** The countries in the order of their entity names, without the unlisted ones. */
  final List<Country> countries;

  /** Every way a country may be named, normalized by {@link #key(String)}. */
  private final Map<String, Country> byKey;

  /** The members of each class (continents and further classes), in the order of the table. */
  final Map<String, List<Country>> classes;

  /** The continents, also those which no country of the table belongs to, sorted. */
  static final List<String> CONTINENTS = List.of("Africa", "Antarctica", "Asia", "Europe",
      "NorthAmerica", "Oceania", "SouthAmerica");

  private CountryTable(List<Country> all) {
    List<Country> countries = new ArrayList<Country>();
    for (Country c : all) {
      if (!c.classes.contains(UNLISTED)) {
        countries.add(c);
      }
    }
    this.countries = Collections.unmodifiableList(countries);
    Map<String, Country> byKey = new HashMap<String, Country>();
    // the lookups of lower priority first, so that an entity name always wins
    for (Country c : all) {
      if (!isMissing(c.code)) {
        byKey.put(key(c.code), c);
      }
      if (!isMissing(c.unCode)) {
        byKey.put(key(c.unCode), c);
      }
      byKey.put(key(c.fullName), c);
      byKey.put(key(c.name), c);
    }
    for (Country c : all) {
      byKey.put(key(c.entity), c);
    }
    byKey.remove("");
    this.byKey = byKey;
    Map<String, List<Country>> classes = new LinkedHashMap<String, List<Country>>();
    for (String continent : CONTINENTS) {
      classes.put(continent, new ArrayList<Country>());
    }
    // the classes have the listed countries only
    for (Country c : countries) {
      if (!c.continent.isEmpty()) {
        classes.computeIfAbsent(c.continent, k -> new ArrayList<Country>()).add(c);
      }
      for (String cls : c.classes) {
        classes.computeIfAbsent(cls, k -> new ArrayList<Country>()).add(c);
      }
    }
    this.classes = classes;
  }

  static CountryTable get() {
    return Holder.TABLE;
  }

  /** The country of a name, an entity name or an ISO code, or <code>null</code>. */
  Country country(String name) {
    return byKey.get(key(name));
  }

  /** The members of a class, or <code>null</code> if there is no such class. */
  List<Country> members(String className) {
    return classes.get(className);
  }

  /**
   * Whether a code of the table is a missing value, written as <code>Missing[reason]</code>.
   */
  static boolean isMissing(String code) {
    return code.startsWith("Missing[") && code.endsWith("]");
  }

  /** Lower case letters and digits only, for matching names. */
  static String key(String name) {
    StringBuilder buf = new StringBuilder(name.length());
    for (char c : name.toLowerCase(Locale.ROOT).toCharArray()) {
      if (Character.isLetterOrDigit(c)) {
        buf.append(c);
      }
    }
    return buf.toString();
  }

  static List<String> split(String text, char separator) {
    return split(text, separator, false);
  }

  /**
   * The fields of a text separated by a character.
   *
   * @param keepEmpty keep empty fields, otherwise they are dropped
   */
  static List<String> split(String text, char separator, boolean keepEmpty) {
    List<String> fields = new ArrayList<String>();
    int start = 0;
    while (true) {
      int end = text.indexOf(separator, start);
      String field = end < 0 ? text.substring(start) : text.substring(start, end);
      if (keepEmpty || !field.isEmpty()) {
        fields.add(field);
      }
      if (end < 0) {
        return fields;
      }
      start = end + 1;
    }
  }

  /** Read the lines of a gzipped table resource next to this class, without the header. */
  static List<String[]> readRows(String resource) {
    List<String[]> rows = new ArrayList<String[]>();
    try (InputStream in = CountryTable.class.getResourceAsStream(resource)) {
      if (in == null) {
        throw new IllegalStateException("missing resource " + resource);
      }
      BufferedReader reader = new BufferedReader(
          new InputStreamReader(new GZIPInputStream(in, 1 << 16), StandardCharsets.UTF_8));
      String line;
      while ((line = reader.readLine()) != null) {
        if (line.isEmpty() || line.charAt(0) == '#') {
          continue;
        }
        rows.add(split(line, '\t', true).toArray(new String[0]));
      }
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
    return rows;
  }

  private static CountryTable load() {
    List<Country> countries = new ArrayList<Country>();
    for (String[] row : readRows(RESOURCE)) {
      countries.add(new Country(row));
    }
    return new CountryTable(countries);
  }
}
